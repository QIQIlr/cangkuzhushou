def 回(全部, 列):
    """列 = [今天, 昨天, …]"""
    天 = {d - timedelta(days=k): v for k, v in enumerate(列)}
    return {"全部": 全部, "天": 天, "起点": d - timedelta(days=len(列) - 1), "对上": sum(列) == 全部, "差": 全部 - sum(列)}



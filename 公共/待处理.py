def _区起点(数据, 类们, 区):
    起点们 = [数据[类][区]["起点"] for 类 in 类们 if 数据.get(类, {}).get(区, "失败") != "失败"]
    return min(起点们) if 起点们 else None


def _值(数据, 类, 区, 日):
    """某类某区某天的数。查过就用查到的；没查（在起点之前）且这个区对上了 → 0；没对上 → “—”。"""
    r = 数据.get(类, {}).get(区, "失败")
    if r == "失败":
        return "失败"
    if 日 in r["天"]:
        return r["天"][日]
    return 0 if r["对上"] else "—"


def _数(v):
    """格子的值 → (数字或 None, 是不是“至少”)。"938+" → (938, True)；"失败"/"—" → (None, True)。"""
    if isinstance(v, int):
        return v, False
    s = str(v).replace("**", "")
    if s.endswith("+") and s[:-1].isdigit():
        return int(s[:-1]), True
    return None, True


def _加(值们, 至少=False):
    """几格相加。至少=False（飞书卡片，照旧）：有一格“失败”合计就是“失败”。
    至少=True（窗口和 Excel，小柒 2026-10-28 确认效果图）：都查到 → 数字；全都没查到 → “失败”；
    有的没查到（或对不上）→ “已查到的和 +”，意思是“至少这么多”。只有没查到的那格本身写“失败”。"""
    if not 至少:
        if any(v == "失败" for v in 值们):
            return "失败"
        if any(v == "—" for v in 值们):
            数 = [v for v in 值们 if isinstance(v, int)]
            return f"{sum(数)}+" if 数 else "—"
        return sum(值们)
    if 值们 and all(v == "失败" for v in 值们):
        return "失败"
    数们 = [_数(v) for v in 值们]
    if not any(至少 for _, 至少 in 数们):
        return sum(值们)
    有数 = [n for n, _ in 数们 if n is not None]
    if 有数:
        return f"{sum(有数)}+"
    return "失败" if any(v == "失败" for v in 值们) else "—"


def 没查到的格(结果, 区们, 类们):
    """["单箱拣货 E区", ...]：这张表里没查到的格子。"""
    数据 = 结果["数据"]
    return [f"{类 + ' ' if 类 else ''}{区}" for 类 in 类们 for 区 in 区们 if 数据.get(类, {}).get(区, "失败") == "失败"]


def 做组表(结果, 组名, 区们, 类们, 至少=False):
    """一个仓库（或单区）的表：行 = 日期（起点 → 今天）+ 合计；列 = 各区 +（合计）。返回 (列名, 行们, 提醒们)。
    至少=True：窗口和 Excel 用——没查到的格子写“失败”，受影响的合计写“N+”（见 _加）。飞书卡片用 至少=False（照旧）。"""
    数据 = 结果["数据"]
    今天 = 结果["开始时间"].date()
    起点们 = [s for 区 in 区们 if (s := _区起点(数据, 类们, 区))]
    起点 = min(起点们) if 起点们 else 今天
    日们 = [起点 + timedelta(days=k) for k in range((今天 - 起点).days + 1)]
    多区 = len(区们) > 1
    列名 = ["日期"] + 区们 + ([f"{组名.replace('仓库', '')}合计"] if 多区 else [])
    行们 = []
    for 日 in 日们:
        值们 = [_加([_值(数据, 类, 区, 日) for 类 in 类们], 至少) for 区 in 区们]
        名 = f"{日:%m/%d} 周{星期[日.weekday()]}" + ("（今天）" if 日 == 今天 else "")
        行们.append([名] + 值们 + ([_加(值们, 至少)] if 多区 else []))
    总们 = [_加([(数据[类][区]["全部"] if 数据.get(类, {}).get(区, "失败") != "失败" else "失败") for 类 in 类们], 至少)
            for 区 in 区们]
    # 前面全是 0 的日子只留一行（作为“从这天起清空了”的起点），不然表格很长
    第一个有数 = next((i for i, 行 in enumerate(行们) if any(v not in (0, "0") for v in 行[1:])), len(行们))
    行们 = 行们[max(0, 第一个有数 - 1):]
    更早 = 没对上的(结果, 区们, 类们)
    if 至少 and 更早["数"]:
        # 窗口和 Excel（小柒 2026-10-29 确认效果图）：最上面一行“X 之前（没对上）M”，各行加起来 = 合计。飞书卡片不加（照旧）
        值们 = [_加([("失败" if 数据.get(类, {}).get(区, "失败") == "失败" else _没对上(数据[类][区])) for 类 in 类们], 至少)
              for 区 in 区们]
        行们.insert(0, [更早["行名"]] + 值们 + ([_加(值们, 至少)] if 多区 else []))
    行们.append(["**合计**"] + [f"**{v}**" for v in 总们] + ([f"**{_加(总们, 至少)}**"] if 多区 else []))
    提醒们 = []
    for 区 in 区们:
        for 类 in 类们:
            r = 数据.get(类, {}).get(区, "失败")
            if r != "失败" and not r["对上"]:
                类字 = f"{类}" if 类 else ""
                if r["差"] < 0:   # 比总数多：查的时候任务有变动（小柒 2026-10-29 定的说法）
                    提醒们.append(f"⚠ {区}{类字}：查的过程中任务有变动，各天合计比总数多 {-r['差']} 条（不是漏查）")
                    continue
                查到 = r.get("查到", r["起点"])
                if 至少:     # 窗口的说法（效果图）
                    提醒们.append(f"⚠ {区}{类字}：往前一天天查到 {查到:%m/%d}，有 {r['差']} 单对不上日期（不在这几天里，"
                                 f"可能是更早积压的任务，或者时间比较特殊），请到 WMS 里看一下。")
                    continue
                提醒们.append(f"⚠ {区}{类字}：往前查到 {查到:%m/%d}，还有 {r['差']} 条对不上（可能是更早积压的任务，"
                             f"或者时间比较特殊），请到 WMS 里看一下")
    if 至少 and 更早["数"]:
        提醒们.append(f"⚠ 表格里“{更早['行名']}”这一行就是这 {更早['数']} 单；各行加起来 = 合计。")
    return 列名, 行们, 提醒们


def 没对上的(结果, 区们, 类们):
    """这张表里没对上日期的单子：{数, 早于（最晚的那个“查到”日）, 行名}。"""
    数据 = 结果["数据"]
    数, 日们 = 0, set()
    for 类 in 类们:
        for 区 in 区们:
            r = 数据.get(类, {}).get(区, "失败")
            if _没对上(r):
                数 += _没对上(r)
                日们.add(r.get("查到", r["起点"]))
    早于 = max(日们) if 日们 else None
    行名 = f"{早于:%m/%d} 之前（没对上）" if len(日们) == 1 else "更早（没对上）"
    return {"数": 数, "早于": 早于, "行名": 行名}


def 组成消息(配置, 结果, 文件夹名):
    名 = 模块参数.显示名(配置["模块名"])   # 窗口里改过的名字
    时间 = 结果["开始时间"]
    类们 = list(配置["类别们"])
    卡片们, 表们, 全部备注, 文字段 = [], [], [], []
    共同备注 = []
    有失败格 = any(v == "失败" for 类 in 结果["数据"] for v in 结果["数据"][类].values())
    # 飞书卡片照旧（2026-10-29 只改窗口和 Excel）：只是“没对上日期”的不完整，卡片还按以前的“成功”写
    卡片状态 = "成功" if 结果["状态"] == "不完整" and not 有失败格 else 结果["状态"]
    if 卡片状态 != "成功":
        共同备注.append(f"⚠ 状态：{卡片状态}" + ("（标“失败”的格子没查到，不是 0）" if 卡片状态 == "不完整" else ""))
        for e in 结果.get("错误列表", []):
            共同备注.append(e.一句话(名))
        共同备注.append(f"日志：{文件夹名}")
    颜色基 = "red" if 卡片状态 == "失败" else ("orange" if 卡片状态 != "成功" else "blue")
    Excel表们 = []
    结论们, 数量表们, 对不上们 = [], [], []
    for 句 in 结果.get("范围提醒", []):   # 旧设置里有不合规则的勾选：已按规则去掉，在结果里说一句
        共同备注.insert(0, f"⚠ 查询范围按规则整理：{句}（请到模块设置里确认一下）")
        对不上们.append(f"查询范围按规则整理：{句}（请到模块设置里确认一下）")
    for 组名, 区们 in 结果["组们"] or [("查询范围", [])]:
        标题 = f"{名} · {组名}（截至 {时间:%m/%d %H:%M}）"
        if not 结果["数据"]:
            卡片们.append(表格.组卡片(标题, [表格.文字元素("\n".join(共同备注) or "没有查到数据")], 颜色基))
            文字段.append(标题 + "\n" + "\n".join(共同备注))
            continue
        列名, 行们, 提醒们 = 做组表(结果, 组名, 区们, 类们)
        备注 = 提醒们 + 共同备注
        元素 = [表格.表格元素(列名, 行们)]
        分表 = []
        if len(类们) > 1:   # 待拣货：合箱、单箱分开的数字放折叠条（飞书不允许折叠条里放表格，用对齐文字）
            for 类 in 类们:
                列2, 行2, _ = 做组表(结果, 组名, 区们, [类])
                元素.append(表格.折叠面板(f"**{类}**", [表格.代码块(表格.文字表格(列2, 行2))]))
                分表.append((f"{组名} · {类}", 列2, 行2))
        元素 += [表格.文字元素(句) for 句 in 备注]
        颜色 = "orange" if 颜色基 == "blue" and 提醒们 else 颜色基
        卡片们.append(表格.组卡片(标题, 元素, 颜色))
        表们.append((标题, 列名, 行们))
        全部备注 += 备注
        文字段.append(标题 + "\n" + 表格.文字表格(列名, 行们) + ("\n" + "\n".join(备注) if 备注 else ""))
        # —— 窗口和 Excel（小柒 2026-10-28 确认效果图）：只有没查到的格子写“失败”，受影响的合计写“N+”（至少这么多）——
        列W, 行W, 提醒W = 做组表(结果, 组名, 区们, 类们, 至少=True)
        分表W = [(类, *做组表(结果, 组名, 区们, [类], 至少=True)[:2]) for 类 in 类们] if len(类们) > 1 else []
        Excel表们.append((组名, 列W, 行W))
        for 类, 列2, 行2 in 分表W:
            Excel表们.append((f"{组名}_{类}", 列2, 行2))
        合计 = str(行W[-1][-1]).replace("**", "")
        最早 = next((str(行[0]).split(" ")[0] for 行 in 行W[:-1] if any(v not in (0, "0") for v in 行[1:])), None)
        缺格 = 没查到的格(结果, 区们, 类们)
        更早 = 没对上的(结果, 区们, 类们)
        没对上句 = f"其中 {更早['数']} 单没对上日期（早于 {更早['早于']:%m/%d}）" if 更早["数"] else ""
        今天行 = next((行 for 行 in 行W if "（今天）" in str(行[0])), None)
        今天数 = 今天行[-1] if 今天行 and isinstance(今天行[-1], int) else 0
        if 合计 == "失败":
            结论们.append(f"{组名}没查到")
        elif 缺格:
            结论们.append(f"{组名}至少 {合计.rstrip('+')} 单；{'、'.join(缺格)} 没查到（不是 0）" + (f"；{没对上句}" if 没对上句 else ""))
        elif 没对上句:          # 小柒 2026-10-29 确认效果图
            结论们.append(f"{组名}共 {合计} 单" + (f"（今天 {今天数} 单）" if 今天数 else "") + f"，{没对上句}")
        else:
            结论们.append(f"{组名}{名} {合计} 单" + (f"，最早是 {最早} 的" if 最早 and 合计 != "0" else ""))
        if 缺格 and 合计 != "失败":
            对不上们.append(f"没查到的格子：{组名} · {'、'.join(缺格)}（不是 0）。其他格子都查到了，照常显示；"
                         f"带“+”的数表示“至少这么多”（没查到的那格不在里面）。")
        数据 = 结果["数据"]
        全对上 = all(数据.get(类, {}).get(区, "失败") != "失败" and 数据[类][区]["对上"] for 类 in 类们 for 区 in 区们)
        数量表们.append({"名": 组名, "起点": 全对上,
                      "视图们": [("合计", 列W, 行W)] + [(类, 列2, 行2) for 类, 列2, 行2 in 分表W]})
        对不上们 += 提醒W          # 窗口橙框用窗口的说法；飞书卡片的备注还是 提醒们（照旧）
    附件 = None
    if Excel表们:
        try:
            from pathlib import Path
            附件 = str(Path(__file__).resolve().parent.parent / "日志" / 文件夹名 / f"{名}_{时间:%Y%m%d_%H%M}.xlsx")
            表格.存Excel多表(附件, f"{名}（截至 {时间:%m/%d %H:%M}）", Excel表们, list(dict.fromkeys(全部备注)))
        except Exception:
            附件 = None
    去重备注 = list(dict.fromkeys(全部备注 or 共同备注))
    if 结果["状态"] == "失败":
        结论 = f"这次没查到{名}的数量（不是 0）"
    else:
        说过 = any("没查到" in 句 for 句 in 结论们)
        结论 = "；".join(结论们) + ("；标“失败”的格子没查到（不是 0）" if 有失败格 and not 说过 else "")
    消息 = {"文字": "\n\n".join(文字段), "卡片们": 卡片们, "附件": 附件,
            "标题": f"{名}（截至 {时间:%m/%d %H:%M}）", "备注": [x.replace("**", "") for x in 去重备注],
            "表们": 表们, "结论": 结论, "提醒们": list(dict.fromkeys(对不上们)), "数量表们": 数量表们}
    if 结果["状态"] == "不完整" and 结果.get("数量") is not None and any(v == "失败" for 类 in 结果["数据"] for v in 结果["数据"][类].values()):
        消息["显示数量"] = f"{结果['数量']}+"     # 窗口左边的数字：有格子没查到时写“至少”
    return 消息, ""

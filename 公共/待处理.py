def 运行(配置, 页面, 记录, 参数=None):
    """配置：模块名、任务状态（文字和代码）、类别们 {任务大类: 代码}（None = 不选，保持“全部”）、
    时间框（按天查用哪个日期框）、日期参数（WMS 网址里这个日期的名字）。"""
    参数 = 参数 or 配置["默认参数"]
    开始时间 = datetime.now()
    今天 = 开始时间.date()
    组们 = 展开范围(参数.get("查询范围"))
    区们 = 查询范围.要查的区(参数.get("查询范围"))
    范围提醒 = 查询范围.整理(参数.get("查询范围"))[1]
    数据 = {类: {} for 类 in 配置["类别们"]}   # 数据[类][区] = 回查结果 或 "失败"
    错误 = []
    名 = 配置["模块名"]
    if 范围提醒:
        记录.写("查询范围按规则整理：" + "；".join(范围提醒))
    if not 区们:
        return 失败结果(配置, 自动化错误(设置有误, f"查询范围是空的（设置里是：{参数.get('查询范围')}），不能查。"), 开始时间, 参数)
    try:
        with 记录.步骤("进入 仓库管理 → 数据管理 → 任务管理"):
            进入页面(页面, ["仓库管理", "数据管理", "任务管理"], 等待接口=查询接口)
        with 记录.步骤(f"展开更多条件，任务状态选“{配置['任务状态']}”，清空创建时间"):
            页面.get_by_text("展开").first.click()
            页面.wait_for_timeout(800)
            下拉选择(页面, "任务状态", 配置["任务状态"])
            清空日期(页面, "创建时间")
        with 记录.步骤("读取“所属区域”的选项"):
            选项 = [x for x in 下拉选项(页面, "所属区域") if x != "全部"]
            if 选项:
                模块参数.保存区域选项(选项)
    except 自动化错误 as e:
        return 失败结果(配置, e, 开始时间, 参数)

    查询器 = 计数查询器(页面, 记录)
    停下 = False          # WMS 弹出账号/系统提示：后面的区、类都不再查（体检 2026-10-28）
    for 类, 代码 in 配置["类别们"].items():
        if 停下:
            break
        类名 = 类 or "全部任务"
        if 类:
            try:
                with 记录.步骤(f"任务大类选“{类}”"):
                    下拉选择(页面, "任务大类", 类)
            except 自动化错误 as e:
                错误.append(e)
                for 区 in 区们:
                    数据[类][区] = "失败"
                停下 = e.类型 in 立刻停下
                continue
        for 区 in 区们:
            期望 = {"taskCategories": 代码, "taskStatus": 配置["状态码"], "shelvesRegionNum": 区.replace("区", ""),
                    "日期参数": 配置["日期参数"], "日期范围": None}
            try:
                with 记录.步骤(f"{类名} {区}：清空{配置['时间框']}，查全部总数，再按天往前查"):
                    下拉选择(页面, "所属区域", 区)

                    def 查全部():
                        清空日期(页面, 配置["时间框"])
                        数 = 查询器.查(期望)
                        记录.写(f"    全部：{数}")
                        return 数

                    def 查天(日):
                        范围 = (f"{日:%Y-%m-%d} 00:00:00", f"{日:%Y-%m-%d} 23:59:59")
                        填日期(页面, 配置["时间框"], *范围)
                        数 = 查询器.查({**期望, "日期范围": 范围})
                        记录.写(f"    {日:%m/%d}：{数}")
                        return 数
                    结果 = 回查(查天, 查全部, 今天, 记录, f"{类名} {区} ")
                    清空日期(页面, 配置["时间框"])
                    数据[类][区] = 结果
                    记录.写(f"    起点 {结果['起点']:%m/%d}，" + ("各天之和 = 全部 ✔" if 结果["对上"] else f"还差 {结果['差']} 条 ⚠"))
            except 自动化错误 as e:
                数据[类][区] = "失败"
                错误.append(e)
                if e.类型 in 立刻停下:
                    停下 = True
                    记录.写("    WMS 弹出了提示，按规矩立刻停下，后面的区不再查")
                    break
                try:
                    清空日期(页面, 配置["时间框"])
                except Exception:
                    # 清不掉也别把整次运行搞崩：下一个区会重新选日期；万一带了旧条件，任务查询._核对 会报“时间条件不对”
                    记录.写("    （清空日期没成功，继续查下一个区；如果条件没清掉，下一个区会报“时间条件不对”）")
    for 类 in 数据:          # 停下时没查的格子记“失败”（不是 0）
        for 区 in 区们:
            数据[类].setdefault(区, "失败")

    return {**算状态(数据), "开始时间": 开始时间,
            "组们": 组们, "数据": 数据, "错误信息": "；".join(e.一句话(名) for e in 错误), "错误列表": 错误,
            "范围提醒": 范围提醒}


def _没对上(r):
    """往前查到最后还差几条（总数 > 各天之和）；对上了、或者是“各天之和 > 总数”（任务在变动）都算 0。"""
    return r["差"] if r != "失败" and not r["对上"] and r["差"] > 0 else 0


def 算状态(数据):
    """{状态, 数量}。全没查到 = 失败；有格子没查到 = 不完整；
    有单子没对上日期（往前查到最后总数还比各天之和多）也是不完整（小柒 2026-10-29 确认效果图），数量照常是总数。"""
    格们 = [v for 类 in 数据 for v in 数据[类].values()]
    失败数 = sum(1 for v in 格们 if v == "失败")
    状态 = "失败" if 格们 and 失败数 == len(格们) else ("不完整" if 失败数 else "成功")
    if 状态 == "成功" and any(_没对上(v) for v in 格们):
        状态 = "不完整"
    合计 = sum(v["全部"] for v in 格们 if v != "失败")
    return {"状态": 状态, "数量": None if 状态 == "失败" else 合计}



# 职责：“待处理任务”三个模块（待审核、待拣货、待增值）共用的查询和出表逻辑。
#   审核 → 拣货 → 增值 是连贯的流程，三个模块查法一样，只是条件不同（见各模块文件里的“配置”）。
#
# 查法（小柒 2026-10-23 确认）：
#   每个区：先清空时间查一次 = 全部总数；再从今天起一天天往前查（今天是 0 不算停止点）；
#   查到某天是 0、并且已查各天之和 = 全部总数 → 停，这一天就是表格起点；
#   查到 0 但之和还不够（中间空了一天）→ 继续往前，最多再查 7 天，直到对上；
#   7 天内还对不上 → 停，标 ⚠“X 日之前还有 N 条未处理”。最多往前 60 天。
#   待拣货有两类（合箱、单箱）：各自按上面规则查，合计的起点 = 两者里更早的那个（更早的日子两类都已证明是 0）。
#
# 区域按仓库：瑞江仓库 = D区 + E区，松户仓库 = A区 + C区 + F区；B区 是测试区，可以单独选。
#   “所属区域”一次只能选一个区，所以分区查完再相加。每个仓库（或单独选的区）一张表、一张卡片。
#
# 查询核对、防连点、失败不记 0：见 公共\任务查询.py。
from datetime import datetime, timedelta

from 公共 import 模块参数, 表格
from 公共.wms import 进入页面
from 公共.任务查询 import 计数查询器, 查询接口
from 公共.表单 import 下拉选择, 下拉选项, 填日期, 清空日期
from 公共.错误 import 自动化错误

仓库 = {"瑞江仓库": ["D区", "E区"], "松户仓库": ["A区", "C区", "F区"]}
范围选项 = ["瑞江仓库", "松户仓库", "A区", "B区", "C区", "D区", "E区", "F区"]
最多往前天数 = 60
对不上时多查天数 = 7
星期 = "一二三四五六日"


def 展开范围(选择):
    """["瑞江仓库", "B区"] → [("瑞江仓库", ["D区", "E区"]), ("B区", ["B区"])]"""
    组们 = []
    for 名 in 选择:
        组们.append((名, 仓库.get(名, [名])))
    return 组们


def 回查(查天, 查全部, 今天, 记录=None, 标签=""):
    """按规则一天天往前查。查天(日期) → 数字；查全部() → 全部总数（清空时间查）。
    返回 {全部, 天: {日期: 数}, 起点, 对上, 差}。
    任务一直在实时增减，所以碰到 0 但和总数对不上时，会先重新查一次总数再判断，避免误报。"""
    全部 = 查全部()
    天 = {}
    和 = 0
    第一个零 = None
    for n in range(最多往前天数 + 1):
        日 = 今天 - timedelta(days=n)
        天[日] = 查天(日)
        和 += 天[日]
        if n > 0 and 天[日] == 0:
            if 和 != 全部:
                # 对不上时先排除“实时变化”：今天的单数和总数都重查一次（新任务一般都是今天创建的）
                新今天 = 查天(今天)
                新 = 查全部()
                if (新 != 全部 or 新今天 != 天[今天]) and 记录:
                    记录.写(f"    {标签}数字刚才变了：总数 {全部} → {新}，今天 {天[今天]} → {新今天}（任务在实时增减）")
                和 += 新今天 - 天[今天]
                天[今天] = 新今天
                全部 = 新
            if 和 == 全部:
                return {"全部": 全部, "天": 天, "起点": 日, "对上": True, "差": 0}
            if 第一个零 is None:
                第一个零 = 日
                if 记录:
                    记录.写(f"    {标签}{日:%m/%d} 是 0，但还差 {全部 - 和} 条，继续往前最多查 {对不上时多查天数} 天")
        if 第一个零 is not None and (第一个零 - 日).days >= 对不上时多查天数:
            break
    最早 = min(天)
    if 记录:
        记录.写(f"    {标签}查到 {最早:%m/%d} 还差 {全部 - 和} 条，停止往前查")
    # 纠错没成功：表格起点 = 第一次遇到的 0 日；为了纠错多查的那些天不输出（小柒 2026-10-23）
    起点 = 第一个零 or 最早
    return {"全部": 全部, "天": 天, "起点": 起点, "对上": 和 == 全部, "差": 全部 - 和, "查到": 最早}


def 失败结果(配置, e, 开始时间, 参数=None):
    参数 = 参数 or 配置["默认参数"]
    return {"状态": "失败", "数量": None, "开始时间": 开始时间, "组们": 展开范围(参数["查询范围"]),
            "数据": {}, "错误信息": e.一句话(配置["模块名"]), "错误列表": [e]}


def 运行(配置, 页面, 记录, 参数=None):
    """配置：模块名、任务状态（文字和代码）、类别们 {任务大类: 代码}（None = 不选，保持“全部”）、
    时间框（按天查用哪个日期框）、日期参数（WMS 网址里这个日期的名字）。"""
    参数 = 参数 or 配置["默认参数"]
    开始时间 = datetime.now()
    今天 = 开始时间.date()
    组们 = 展开范围(参数["查询范围"])
    区们 = list(dict.fromkeys(区 for _, 区们 in 组们 for 区 in 区们))
    数据 = {类: {} for 类 in 配置["类别们"]}   # 数据[类][区] = 回查结果 或 "失败"
    错误 = []
    名 = 配置["模块名"]
    try:
        with 记录.步骤("进入 仓库管理 → 数据管理 → 任务管理"):
            进入页面(页面, ["仓库管理", "数据管理", "任务管理"], 等待接口=查询接口)
        with 记录.步骤(f"展开更多条件，任务状态选“{配置['任务状态']}”，清空创建时间"):
            页面.get_by_text("展开").first.click()
            页面.wait_for_timeout(800)
            下拉选择(页面, "任务状态", 配置["任务状态"])
            清空日期(页面, "创建时间")
        with 记录.步骤("读取“所属区域”的选项"):
            选项 = [x for x in 下拉选项(页面, "所属区域") if x != "全部"]
            if 选项:
                模块参数.保存区域选项(选项)
    except 自动化错误 as e:
        return 失败结果(配置, e, 开始时间, 参数)

    查询器 = 计数查询器(页面, 记录)
    for 类, 代码 in 配置["类别们"].items():
        类名 = 类 or "全部任务"
        if 类:
            try:
                with 记录.步骤(f"任务大类选“{类}”"):
                    下拉选择(页面, "任务大类", 类)
            except 自动化错误 as e:
                错误.append(e)
                for 区 in 区们:
                    数据[类][区] = "失败"
                continue
        for 区 in 区们:
            期望 = {"taskCategories": 代码, "taskStatus": 配置["状态码"], "shelvesRegionNum": 区.replace("区", ""),
                    "日期参数": 配置["日期参数"], "日期范围": None}
            try:
                with 记录.步骤(f"{类名} {区}：清空{配置['时间框']}，查全部总数，再按天往前查"):
                    下拉选择(页面, "所属区域", 区)

                    def 查全部():
                        清空日期(页面, 配置["时间框"])
                        数 = 查询器.查(期望)
                        记录.写(f"    全部：{数}")
                        return 数

                    def 查天(日):
                        范围 = (f"{日:%Y-%m-%d} 00:00:00", f"{日:%Y-%m-%d} 23:59:59")
                        填日期(页面, 配置["时间框"], *范围)
                        数 = 查询器.查({**期望, "日期范围": 范围})
                        记录.写(f"    {日:%m/%d}：{数}")
                        return 数
                    结果 = 回查(查天, 查全部, 今天, 记录, f"{类名} {区} ")
                    清空日期(页面, 配置["时间框"])
                    数据[类][区] = 结果
                    记录.写(f"    起点 {结果['起点']:%m/%d}，" + ("各天之和 = 全部 ✔" if 结果["对上"] else f"还差 {结果['差']} 条 ⚠"))
            except 自动化错误 as e:
                数据[类][区] = "失败"
                错误.append(e)
                try:
                    清空日期(页面, 配置["时间框"])
                except Exception:
                    pass

    格们 = [v for 类 in 数据 for v in 数据[类].values()]
    失败数 = sum(1 for v in 格们 if v == "失败")
    状态 = "失败" if 格们 and 失败数 == len(格们) else ("不完整" if 失败数 else "成功")
    合计 = sum(v["全部"] for v in 格们 if v != "失败")
    return {"状态": 状态, "数量": None if 状态 == "失败" else 合计, "开始时间": 开始时间,
            "组们": 组们, "数据": 数据, "错误信息": "；".join(e.一句话(名) for e in 错误), "错误列表": 错误}


# ---------------- 出表 ----------------

def _区起点(数据, 类们, 区):
    起点们 = [数据[类][区]["起点"] for 类 in 类们 if 数据.get(类, {}).get(区, "失败") != "失败"]
    return min(起点们) if 起点们 else None


def _值(数据, 类, 区, 日):
    """某类某区某天的数。查过就用查到的；没查（在起点之前）且这个区对上了 → 0；没对上 → “—”。"""
    r = 数据.get(类, {}).get(区, "失败")
    if r == "失败":
        return "失败"
    if 日 in r["天"]:
        return r["天"][日]
    return 0 if r["对上"] else "—"


def _加(值们):
    if any(v == "失败" for v in 值们):
        return "失败"
    if any(v == "—" for v in 值们):
        数 = [v for v in 值们 if isinstance(v, int)]
        return f"{sum(数)}+" if 数 else "—"
    return sum(值们)


def 做组表(结果, 组名, 区们, 类们):
    """一个仓库（或单区）的表：行 = 日期（起点 → 今天）+ 合计；列 = 各区 +（合计）。返回 (列名, 行们, 提醒们)。"""
    数据 = 结果["数据"]
    今天 = 结果["开始时间"].date()
    起点们 = [s for 区 in 区们 if (s := _区起点(数据, 类们, 区))]
    起点 = min(起点们) if 起点们 else 今天
    日们 = [起点 + timedelta(days=k) for k in range((今天 - 起点).days + 1)]
    多区 = len(区们) > 1
    列名 = ["日期"] + 区们 + ([f"{组名.replace('仓库', '')}合计"] if 多区 else [])
    行们 = []
    for 日 in 日们:
        值们 = [_加([_值(数据, 类, 区, 日) for 类 in 类们]) for 区 in 区们]
        名 = f"{日:%m/%d} 周{星期[日.weekday()]}" + ("（今天）" if 日 == 今天 else "")
        行们.append([名] + 值们 + ([_加(值们)] if 多区 else []))
    总们 = [_加([(数据[类][区]["全部"] if 数据.get(类, {}).get(区, "失败") != "失败" else "失败") for 类 in 类们])
            for 区 in 区们]
    # 前面全是 0 的日子只留一行（作为“从这天起清空了”的起点），不然表格很长
    第一个有数 = next((i for i, 行 in enumerate(行们) if any(v not in (0, "0") for v in 行[1:])), len(行们))
    行们 = 行们[max(0, 第一个有数 - 1):]
    行们.append(["**合计**"] + [f"**{v}**" for v in 总们] + ([f"**{_加(总们)}**"] if 多区 else []))
    提醒们 = []
    for 区 in 区们:
        for 类 in 类们:
            r = 数据.get(类, {}).get(区, "失败")
            if r != "失败" and not r["对上"]:
                类字 = f"{类}" if 类 else ""
                提醒们.append(f"⚠ {区}{类字}：往前查到 {r.get('查到', r['起点']):%m/%d}，还有 {r['差']} 条对不上（可能是更早积压的任务，"
                             f"或者时间比较特殊），请到 WMS 里看一下")
    return 列名, 行们, 提醒们


def 组成消息(配置, 结果, 文件夹名):
    名 = 模块参数.显示名(配置["模块名"])   # 窗口里改过的名字
    时间 = 结果["开始时间"]
    类们 = list(配置["类别们"])
    卡片们, 表们, 全部备注, 文字段 = [], [], [], []
    共同备注 = []
    if 结果["状态"] != "成功":
        共同备注.append(f"⚠ 状态：{结果['状态']}" + ("（标“失败”的格子没查到，不是 0）" if 结果["状态"] == "不完整" else ""))
        for e in 结果.get("错误列表", []):
            共同备注.append(e.一句话(名))
        共同备注.append(f"日志：{文件夹名}")
    颜色基 = "red" if 结果["状态"] == "失败" else ("orange" if 结果["状态"] != "成功" else "blue")
    Excel表们 = []
    for 组名, 区们 in 结果["组们"]:
        标题 = f"{名} · {组名}（截至 {时间:%m/%d %H:%M}）"
        if not 结果["数据"]:
            卡片们.append(表格.组卡片(标题, [表格.文字元素("\n".join(共同备注) or "没有查到数据")], 颜色基))
            文字段.append(标题 + "\n" + "\n".join(共同备注))
            continue
        列名, 行们, 提醒们 = 做组表(结果, 组名, 区们, 类们)
        备注 = 提醒们 + 共同备注
        元素 = [表格.表格元素(列名, 行们)]
        分表 = []
        if len(类们) > 1:   # 待拣货：合箱、单箱分开的数字放折叠条（飞书不允许折叠条里放表格，用对齐文字）
            for 类 in 类们:
                列2, 行2, _ = 做组表(结果, 组名, 区们, [类])
                元素.append(表格.折叠面板(f"**{类}**", [表格.代码块(表格.文字表格(列2, 行2))]))
                分表.append((f"{组名} · {类}", 列2, 行2))
        元素 += [表格.文字元素(句) for 句 in 备注]
        颜色 = "orange" if 颜色基 == "blue" and 提醒们 else 颜色基
        卡片们.append(表格.组卡片(标题, 元素, 颜色))
        表们.append((标题, 列名, 行们))
        Excel表们.append((组名, 列名, 行们))
        for 表名, 列2, 行2 in 分表:
            Excel表们.append((表名.replace(" · ", "_"), 列2, 行2))
        全部备注 += 备注
        文字段.append(标题 + "\n" + 表格.文字表格(列名, 行们) + ("\n" + "\n".join(备注) if 备注 else ""))
    附件 = None
    if Excel表们:
        try:
            from pathlib import Path
            附件 = str(Path(__file__).resolve().parent.parent / "日志" / 文件夹名 / f"{名}_{时间:%Y%m%d_%H%M}.xlsx")
            表格.存Excel多表(附件, f"{名}（截至 {时间:%m/%d %H:%M}）", Excel表们, list(dict.fromkeys(全部备注)))
        except Exception:
            附件 = None
    去重备注 = list(dict.fromkeys(全部备注 or 共同备注))
    return {"文字": "\n\n".join(文字段), "卡片们": 卡片们, "附件": 附件,
            "标题": f"{名}（截至 {时间:%m/%d %H:%M}）", "备注": [x.replace("**", "") for x in 去重备注],
            "表们": 表们}, ""

# ---------------- 待增值：拆成“合箱增值 / 单箱增值”查（2026-11-01，方案第 4～6 节） ----------------
# 小柒 2026-11-01 的要求：待增值要能看出合箱多少、单箱多少（窗口小卡片、Excel 两张分表 + 核对表、
# 飞书两个折叠条），并且核对“合箱 + 单箱 = 任务小类全部”，差 5 单以内算对上。
# 做法（方案 §4 D1–D3）：每个区按 合箱增值 → 单箱增值 → 全部 查三轮；交给出表 / 快照的主数据仍然只有
# “增值服务”一类（每格 = 合箱 + 单箱），拆开的数字另放 结果["拆分"]，所以 做组表 / 结论 / 快照 一个字不用改。

def _合并两类(甲, 乙):
    """两个 回查() 结果 → 一个同格式结果（方案 5.2 的表）。
    某一天只在一类里出现时：那一类“对上” → 另一边当 0；没对上 → 这一天不放进去（不知道，绝不当 0）。"""
    if 甲 == "失败" or 乙 == "失败":
        return "失败"
    天 = {}
    for 一边 in (甲, 乙):
        for 日, 数 in 一边["天"].items():
            天[日] = 天.get(日, 0) + 数
    for 日 in list(天):
        if 日 not in 甲["天"] and not 甲["对上"]:
            天.pop(日)
        elif 日 not in 乙["天"] and not 乙["对上"]:
            天.pop(日)
    总 = 甲["全部"] + 乙["全部"]
    和 = sum(天.values())
    起点 = min(甲["起点"], 乙["起点"])
    出 = {"全部": 总, "天": 天, "起点": 起点, "对上": 和 == 总, "差": 总 - 和}
    if not 出["对上"]:
        出["查到"] = min(天) if 天 else 起点
    return 出


def _核对结果字(一):
    """Excel 核对表“结果”那一栏怎么写（方案 5.4 第 3 条）。"""
    允许 = 一.get("允许")
    A, B, W, K = 一.get("合箱"), 一.get("单箱"), 一.get("全部"), 一.get("差")
    if A is None or B is None:
        return "合箱或单箱没查到，没核对"
    if W is None:
        return "“全部”没查到，没核对"
    if 一.get("通过"):
        if 一.get("复查"):
            return "复查后对上" if not K else f"复查后差 {K} 单，在允许范围内"
        return "对上" if not K else f"差 {K} 单，在允许范围内（≤{允许}）"
    return f"⚠ 对不上，差 {K} 单"


def _核对表(结果):
    """Excel 的核对表：列 = 区 | 合箱增值 | 单箱增值 | 合箱+单箱 | 全部 | 差 | 结果，每区一行。"""
    核 = 结果.get("拆分核对") or {}
    列 = ["区", "合箱增值", "单箱增值", "合箱+单箱", "全部（任务小类=全部）", "差", "结果"]
    行们 = []
    for 区, 一 in 核.items():
        A, B = 一.get("合箱"), 一.get("单箱")
        和 = None if (A is None or B is None) else A + B
        行们.append([区, _数格(A), _数格(B), _数格(和), _数格(一.get("全部")), _数格(一.get("差")), _核对结果字(一)])
    return 列, 行们



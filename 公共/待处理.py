最多往前天数 = 60
对不上时多查天数 = 7
星期 = "一二三四五六日"


def 展开范围(选择):
    """["瑞江仓库", "B区"] → [("瑞江仓库", ["D区", "E区"]), ("B区", ["B区"])]（按规则整理过）"""
    return 查询范围.展开(选择)


def 回查(查天, 查全部, 今天, 记录=None, 标签=""):
    """按规则一天天往前查。查天(日期) → 数字；查全部() → 全部总数（清空时间查）。
    返回 {全部, 天: {日期: 数}, 起点, 对上, 差}。
    任务一直在实时增减，所以碰到 0 但和总数对不上时，会先重新查一次总数再判断，避免误报。"""
    全部 = 查全部()
    天 = {}
    和 = 0
    第一个零 = None
    for n in range(最多往前天数 + 1):
        日 = 今天 - timedelta(days=n)
        天[日] = 查天(日)
        和 += 天[日]
        if n > 0 and 天[日] == 0:
            if 和 != 全部:
                # 对不上时先排除“实时变化”：今天的单数和总数都重查一次（新任务一般都是今天创建的）
                新今天 = 查天(今天)
                新 = 查全部()
                if (新 != 全部 or 新今天 != 天[今天]) and 记录:
                    记录.写(f"    {标签}数字刚才变了：总数 {全部} → {新}，今天 {天[今天]} → {新今天}（任务在实时增减）")
                和 += 新今天 - 天[今天]
                天[今天] = 新今天
                全部 = 新
            if 和 == 全部:
                return {"全部": 全部, "天": 天, "起点": 日, "对上": True, "差": 0}
            if 和 > 全部:
                # 各天加起来比总数还多：是查的过程中任务有变动，再往前只会加 0，不可能对上 → 马上停（小柒 2026-10-29）
                if 记录:
                    记录.写(f"    {标签}{日:%m/%d} 是 0，各天合计 {和} 比总数 {全部} 多 {和 - 全部} 条（任务在变动），不再往前查")
                起点 = 第一个零 or 日
                return {"全部": 全部, "天": 天, "起点": 起点, "对上": False, "差": 全部 - 和, "查到": 日}
            if 第一个零 is None:
                第一个零 = 日
                if 记录:
                    记录.写(f"    {标签}{日:%m/%d} 是 0，但还差 {全部 - 和} 条，继续往前最多查 {对不上时多查天数} 天")
        if 第一个零 is not None and (第一个零 - 日).days >= 对不上时多查天数:
            break
    最早 = min(天)
    if 记录:
        记录.写(f"    {标签}查到 {最早:%m/%d} 还差 {全部 - 和} 条，停止往前查")
    # 纠错没成功：表格起点 = 第一次遇到的 0 日；为了纠错多查的那些天不输出（小柒 2026-10-23）
    起点 = 第一个零 or 最早
    return {"全部": 全部, "天": 天, "起点": 起点, "对上": 和 == 全部, "差": 全部 - 和, "查到": 最早}



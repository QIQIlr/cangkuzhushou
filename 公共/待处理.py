# 职责：“待处理任务”三个模块（待审核、待拣货、待增值）共用的查询和出表逻辑。
#   审核 → 拣货 → 增值 是连贯的流程，三个模块查法一样，只是条件不同（见各模块文件里的“配置”）。
#
# 查法（小柒 2026-10-23 确认）：
#   每个区：先清空时间查一次 = 全部总数；再从今天起一天天往前查（今天是 0 不算停止点）；
#   查到某天是 0、并且已查各天之和 = 全部总数 → 停，这一天就是表格起点；
#   查到 0 但之和还不够（中间空了一天）→ 继续往前，最多再查 7 天，直到对上；
#   7 天内还对不上 → 停，标 ⚠“X 日之前还有 N 条未处理”。最多往前 60 天。
#   查到 0 时各天之和比总数还多（查的过程中任务有变动）→ 马上停，不再多查，标 ⚠“任务有变动，多 N 条”（2026-10-29）。
#   7 天内对不上（总数比各天之和多）时的显示（小柒 2026-10-29 确认效果图）：状态“不完整”（橙色），结论写
#   “X仓库共 N 单（今天 T 单），其中 M 单没对上日期（早于 某日）”，窗口和 Excel 的表格最上面加一行“某日之前（没对上）M”，
#   各行加起来 = 合计。飞书卡片和文字版一样（小柒 2026-10-29 确认卡片效果图）：最上面一句结论、表格首行同上、两句提醒、
#   “⚠ 状态：不完整（M 单没对上日期……）”；待拣货合箱 / 单箱分表也有这一行。
#   待拣货有两类（合箱、单箱）：各自按上面规则查，合计的起点 = 两者里更早的那个（更早的日子两类都已证明是 0）。
#
# 查询范围（仓库 / 单独的区）的规则见 公共\查询范围.py（和无任务包裹共用）。
#   “所属区域”一次只能选一个区，所以分区查完再相加。每个仓库（或单独选的区）一张表、一张卡片。
#
# 查询核对、防连点、失败不记 0：见 公共\任务查询.py。

# 职责：结果页的「和上次比」「今天各次」两段，加上结论条下面那行摘要句（2026-11-01 新增）。
#   数据全部来自 项["变化"]：运行时（公共\追踪.py）就把数字算好、排成一行行字符串了，
#   这里只负责画——不重算、不读文件、不查 WMS。窗口重开后读 上次结果.json 也能照原样画出来。
#   没有 项["变化"]（老结果、第一次运行、算变化出错）时，这里一个零件都不建，页面和以前完全一样。
#   颜色、字号只从 主题.py 取；表块 / 自动排版沿用 数量页 那一套，不另做一套表格。

from PySide6.QtCore import Qt
from PySide6.QtWidgets import QVBoxLayout, QWidget

from 公共.界面 import 主题
from 公共.界面.组件 import 空白提示, 分段
from 公共.结果页.零件 import _标签
from 公共.结果页.数量页 import _数量内容, 表块, 表格排列

色 = 主题.色
字号 = 主题.字号

段名们 = ("这次结果", "和上次比", "今天各次")
当前段 = 0   # 同一次打开的窗口里切模块保持同一段（小柒 2026-11-01 默认）；重开软件回到“这次结果”，不写设置文件


# ---------------- 摘要句 ----------------
def 摘要(项):
    """结论条正下方一行灰字，例如“瑞江仓库比上次（15:23）多 522 单：之前日期的 −118，今天的 +640”。"""
    句 = ((项.get("变化") or {}).get("摘要") or "").strip()
    if not 句:
        return None
    return _标签(句, f"font-size:{字号['说明']}px; color:{色['说明']}; background:transparent;")


# ---------------- 页面分段控件 ----------------
def 段控件():
    """「这次结果｜和上次比｜今天各次」。没变化数据时返回 None（整条不显示）。"""
    return 分段(list(段名们), 当前段 if 0 <= 当前段 < len(段名们) else 0)


def 设段(序):
    global 当前段
    if isinstance(序, int) and 0 <= 序 < len(段名们):
        当前段 = 序


def 内容(项, 段, 状态栏):
    """段 0 = 这次结果（由 __init__ 走原来的分派）；这里只管 1、2。"""
    变化 = 项.get("变化") or {}
    if 段 == 1:
        return 和上次比(变化, 状态栏)
    if 段 == 2:
        return 今天各次(变化, 状态栏)
    return None


# ---------------- 「和上次比」 ----------------
def 和上次比(变化, 状态栏):
    组们 = 变化.get("组们") or []
    if not 组们:
        return None
    表们, 灰句们, 空组们 = [], [], []
    for 组 in 组们:
        比 = 组.get("比较") or {}
        视图们 = [(名, 列, 行) for 名, 列, 行 in (比.get("视图们") or [])]
        if 组.get("空状态") or not 视图们:
            空组们.append(f"{组.get('名', '')}：{组.get('空状态') or '这次没有可比较的数'}")
            continue
        表们.append({"名": f"{组.get('名', '')} · {组.get('标题') or ''}".strip(" ·"),
                    "视图们": 视图们, "起点": False, "变化": True,
                    "视图提示们": 比.get("提示们") or []})     # 每种看法一份提示（合计 / 合箱 / 单箱数字不同）
        if 组.get("灰字"):
            灰句们.append(f"{组.get('名', '')}：{组['灰字']}")
    件们 = []
    if 表们:
        件们.append(_数量内容({"数量表们": 表们}, 状态栏))   # 和「这次结果」同一套排版、同一套列格子
    if 空组们:
        件们.append(_空状态("这次结果还没有可以比较的（第一次记录）", "\n".join(空组们)))
    if 灰句们:
        件们.append(_灰字块(灰句们))
    return _一栏(件们)


# ---------------- 「今天各次」 ----------------
def 今天各次(变化, 状态栏):
    组们 = 变化.get("组们") or []
    流程 = 变化.get("流程") or []
    灰句们 = []
    流程块们 = [表块({"名": f"流程一览 · {项.get('组', '')}（审核 → 拣货 → 增值）",
                    "视图们": [("合计", 项.get("列名") or [], 项.get("行们") or [])],
                    "起点": False, "变化": True}, 状态栏) for 项 in 流程]
    各次块们 = []
    for 组 in 组们:
        各 = 组.get("今天各次") or {}
        if 各.get("列名"):
            各次块们.append(表块({"名": f"{组.get('名', '')} · 今天 {各.get('次数', 1)} 次",
                                "视图们": [("合计", 各["列名"], 各.get("行们") or [])],
                                "起点": False, "变化": True}, 状态栏))
        if 各.get("灰字"):
            灰句们.append(f"{组.get('名', '')}：{各['灰字']}")
    全部块 = 流程块们 + 各次块们
    if not 全部块 and not 灰句们:
        return None
    # 两块表要一样宽、左右对齐（规范）：先量出最宽的一块，再按这个宽度排（必须在排版之前量，排过之后列宽会被拉开）
    宽 = max(b.最小宽() for b in 全部块) if len(全部块) > 1 else None
    件们 = []
    if 流程块们:
        件们.append(表格排列(流程块们, 宽))
    if 各次块们:
        件们.append(表格排列(各次块们, 宽))
    if 灰句们:
        件们.append(_灰字块(灰句们))
    return _一栏(件们)


# ---------------- 小零件 ----------------
def _一栏(件们, 间距=14):
    """把几件竖着摞起来。件要拿满整列宽（表格排列靠自己收到的宽度排版，给固定宽会把表挤没）。"""
    外 = QWidget()
    层 = QVBoxLayout(外)
    层.setContentsMargins(0, 0, 0, 0)
    层.setSpacing(间距)
    for 件 in 件们:
        if 件 is not None:
            层.addWidget(件)
    层.addStretch(1)
    return 外


def _灰字块(句们):
    """表下面的说明：说明字号、次要字颜色（规范），例如旧日期变多了、今天只跑了一次。"""
    外 = QWidget()
    层 = QVBoxLayout(外)
    层.setContentsMargins(0, 0, 0, 0)
    层.setSpacing(4)
    for 句 in 句们:
        层.addWidget(_标签(句, f"font-size:{字号['说明']}px; color:{色['说明']}; background:transparent;"))
    return 外


def _空状态(标题, 说明=""):
    w = 空白提示("时钟", 标题, 说明)
    w.setMinimumHeight(170)
    return w

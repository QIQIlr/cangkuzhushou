# 职责：按顺序运行一个或几个模块（窗口和单独运行某个模块文件都用它）。
# 输入：模块名列表（按运行顺序）、是否显示浏览器、是否允许发飞书。
# 输出：{"结果们", "消息们", "日志文件夹"}；每个模块单独发一条飞书（不合并）。
# 规则：
#   - WMS 只打开一次，各模块依次使用；每个模块开始前回到首页并刷新，互不影响。
#   - 一个模块失败不影响下一个。
#   - 每个模块各有自己的日志文件夹和运行总表一行；运行多个模块时另有一个“主控”日志。
#   - 每个模块读自己的设置（模块参数.json）：查询区域、发到飞书 等。
#
# 模块要提供（约定）：
#   模块名                          中文名，和文件名一样
#   默认参数                        可选，例如 {"区域": ["D区", "E区"]}
#   运行(页面, 记录, 参数) -> 结果    结果至少有 状态、数量、错误信息、错误列表
#   失败结果(错误, 开始时间, 参数)    还没开始查就失败时，给出一份“失败”结果
#   组成消息(结果, 日志文件夹名, 用时) -> (消息, 格式问题)
#       消息是文字；或者是 {"文字", "卡片" 或 "卡片们"（多张）, "附件"(Excel), "表们"[(表名, 列名, 行们)], "备注", "标题"}
import importlib
import time
from datetime import datetime

from 公共 import 模块参数, 飞书
from 公共.wms import WMS首页, 打开WMS
from 公共.日志 import 运行记录
from 公共.错误 import 自动化错误, 归类, 程序出错

成功状态 = ("成功", "无数据")


def 载入模块(名):
    try:
        模块 = importlib.import_module(f"模块.{名}")
        return 模块, 模块参数.读取(名, getattr(模块, "默认参数", {})), None
    except Exception as e:
        return None, 模块参数.读取(名), 自动化错误(程序出错, f"模块文件“{名}.py”载入出错：{type(e).__name__}: {e}")


def _失败(模块, 错误, 开始, 参数):
    if 模块 is None:
        return {"状态": "失败", "数量": None, "开始时间": 开始, "错误信息": 错误.一句话(), "错误列表": [错误]}
    return 模块.失败结果(错误, 开始, 参数)


def 运行模块们(名列表, 可见=False, 发送=True, 显示=True, 等待登录=None, 回报=None, 测试=None):
    """回报(事件, 内容)：窗口版用来显示进度。事件有 开始模块 / 模块完成。
    测试=True（或环境变量 仓库助手_测试=1）：发出去的卡片和文字标题前都加“【测试】”。
    Claude 自测、验证时必须用测试=True；只有小柒自己在窗口/菜单里运行时才发正式消息。"""
    import os
    if 测试 is None:
        测试 = os.environ.get("仓库助手_测试") == "1"
    from playwright.sync_api import sync_playwright
    开始 = datetime.now()
    方式 = ("可见窗口" if 可见 else "后台") + ("，可发飞书" if 发送 else "，不发飞书")
    多个 = len(名列表) > 1
    主控 = 运行记录("主控", 方式 + "；模块：" + "、".join(名列表)) if 多个 else None
    清单 = []   # 每项：[名, 模块, 参数, 记录, 结果, 开始时间]

    def 打印(文字):
        if 显示:
            print(文字, flush=True)

    def 通知(事件, 内容):
        if 回报:
            try:
                回报(事件, 内容)
            except Exception:
                pass

    try:
        with sync_playwright() as p:
            浏览器 = 页面 = None
            打开失败 = None
            首个记录 = 主控 or 运行记录(名列表[0], 方式)
            try:
                with 首个记录.步骤("打开 WMS 并检查登录"):
                    浏览器, 页面 = 打开WMS(p, 可见=可见, 记录=首个记录, 等待登录=等待登录)
            except 自动化错误 as e:
                打开失败 = e
            for 序号, 名 in enumerate(名列表, 1):
                打印(f"\n▶ [{序号}/{len(名列表)}] {名} ……")
                通知("开始模块", (序号, len(名列表), 名))
                模块, 参数, 载入错误 = 载入模块(名)
                记录 = 首个记录 if not 多个 else 运行记录(名, 方式)
                模块开始 = datetime.now()
                if 页面 is not None:
                    记录.页面 = 页面
                if 参数.get("区域"):
                    记录.写(f"查询区域：{'、'.join(参数['区域'])}")
                if 载入错误 or 打开失败:
                    错误 = 载入错误 or 打开失败
                    记录.写(f"没有运行：{错误.原因}")
                    结果 = _失败(模块, 错误, 模块开始, 参数)
                else:
                    try:
                        if 多个:
                            with 记录.步骤("回到 WMS 首页并刷新"):
                                页面.goto(WMS首页)
                                页面.reload()
                                页面.locator(".el-menu").first.wait_for(timeout=15000)
                        结果 = 模块.运行(页面, 记录, 参数)
                    except 自动化错误 as e:
                        结果 = _失败(模块, e, 模块开始, 参数)
                    except Exception as 原始:   # 模块里没想到的错误，也要留下现场
                        记录.保存现场(原始)
                        e = 归类(原始)
                        e.步骤 = e.步骤 or "（不在任何步骤里）"
                        结果 = _失败(模块, e, 模块开始, 参数)
                打印(f"  {结果['状态']}" + (f"，数量 {结果['数量']}" if 结果.get("数量") is not None else ""))
                通知("模块完成", (名, 结果))
                清单.append([名, 模块, 参数, 记录, 结果, 模块开始])
            if 浏览器:
                浏览器.close()
    except Exception as 原始:   # 浏览器本身崩溃之类
        e = 归类(原始)
        (主控 or 运行记录("主控", 方式)).保存现场(原始)
        已跑 = {项[0] for 项 in 清单}
        for 名 in 名列表:
            if 名 not in 已跑:
                模块, 参数, _ = 载入模块(名)
                清单.append([名, 模块, 参数, 运行记录(名, 方式), _失败(模块, e, datetime.now(), 参数), datetime.now()])

    # —— 每个模块：组成消息、发送、写日志 ——
    消息们 = []
    for 名, 模块, 参数, 记录, 结果, 模块开始 in 清单:
        用时 = (datetime.now() - 模块开始).total_seconds()
        卡片们, 附件, 表们, 备注, 标题, 分组 = [], None, [], [], "", None
        try:
            if 模块 is None:
                raise ValueError("模块没有载入")
            消息, 格式问题 = 模块.组成消息(结果, 记录.文件夹名, 用时=用时)
            if 格式问题:
                记录.写(f"消息格式：{格式问题}")
        except Exception as e:
            记录.写(f"组成消息出错：{type(e).__name__}: {e}")
            消息 = f"【{名}】{结果['状态']}\n{结果.get('错误信息', '')}"
        if isinstance(消息, dict):
            卡片们 = 消息.get("卡片们") or ([消息["卡片"]] if 消息.get("卡片") else [])
            附件, 文字 = 消息.get("附件"), 消息.get("文字", "")
            表们, 备注, 标题 = 消息.get("表们", []), 消息.get("备注", []), 消息.get("标题", "")
            分组 = 消息.get("分组")
        else:
            文字 = 消息
        if 测试:   # 自测、验证时发的消息一律标【测试】，和小柒自己运行的正式结果区分开
            for 卡 in 卡片们:
                卡["header"]["title"]["content"] = "【测试】" + 卡["header"]["title"]["content"]
            文字 = "【测试】" + 文字

        if not 发送:
            发送状态, 发送说明 = "未发送", "本次选择不发送"
        elif not 参数.get("发到飞书", True):
            发送状态, 发送说明 = "未发送", "这个模块设置为不发飞书"
        elif not 飞书.可以发送():
            发送状态, 发送说明 = "未发送", "还没设置好飞书（点“设置飞书”）"
        else:
            if any(项["飞书"][0] != "未发送" for 项 in 消息们):
                time.sleep(1)   # 飞书机器人每秒最多 5 条，留点间隔
            记录.写("发送飞书 ……")
            记录.保存发送内容(文字, "（准备发送）" + (f"，{len(卡片们)} 张卡片" if 卡片们 else ""))
            if len(卡片们) > 1:
                记录.写(f"    内容较多，拆成 {len(卡片们)} 张卡片发送（每张不超过 18 KB，不丢内容）")
            发送状态, 发送说明 = 飞书.发送全部(
                卡片们, 文字, 每张=lambda 张, 共, 状, 说: 记录.写(f"    第 {张}/{共} 张：{状}（{说}）"))
        记录.保存发送内容(文字, f"{发送状态}：{发送说明}")
        记录.写(f"飞书：{发送状态}（{发送说明}）")
        摘要 = 结果.get("错误信息", "")
        if 发送状态 in ("失败", "未知"):
            摘要 = (摘要 + "；" if 摘要 else "") + f"飞书{发送状态}：{发送说明}"
        记录.结束(结果["状态"], 结果.get("数量"), 摘要)
        消息们.append({"模块": 名, "状态": 结果["状态"], "文字": 文字, "附件": 附件,
                     "表们": 表们, "备注": 备注, "标题": 标题, "分组": 分组, "卡片们": 卡片们,
                     "飞书": (发送状态, 发送说明), "日志文件夹": str(记录.文件夹)})

    if 主控:
        for 项 in 消息们:
            主控.写(f"{项['模块']}：{项['状态']}，飞书 {项['飞书'][0]}，日志 {项['日志文件夹']}")
        有问题 = [项["模块"] for 项 in 消息们 if 项["状态"] not in 成功状态]
        飞书问题 = [项["模块"] for 项 in 消息们 if 项["飞书"][0] in ("失败", "未知")]
        摘要 = "；".join(x for x in (("有问题的模块：" + "、".join(有问题)) if 有问题 else "",
                                    ("飞书没发成功：" + "、".join(飞书问题)) if 飞书问题 else "") if x)
        主控.结束("成功" if not 有问题 else "有问题", None, 摘要)

    for 项 in 消息们:
        打印("\n" + "=" * 40 + "\n" + 项["文字"] + "\n" + "=" * 40)
        打印(f"飞书：{项['飞书'][0]}（{项['飞书'][1]}）" + (f"    Excel：{项['附件']}" if 项["附件"] else ""))
    打印(f"总用时：{(datetime.now() - 开始).total_seconds():.0f} 秒    日志：{(主控 or 清单[0][3]).文件夹}")
    return {"结果们": [项[4] for 项 in 清单], "消息们": 消息们,
            "日志文件夹": str((主控 or 清单[0][3]).文件夹)}

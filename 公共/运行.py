# 职责：按顺序运行一个或几个模块（窗口和单独运行某个模块文件都用它）。
# 输入：模块名列表（按运行顺序）、是否显示浏览器、是否允许发飞书。
# 输出：{"结果们", "消息们", "日志文件夹"}；每个模块单独发一条飞书（不合并）。
# 规则：
#   - WMS 只打开一次，各模块依次使用；每个模块开始前回到首页并刷新，互不影响。
#   - 一个模块失败不影响下一个。
#   - 每个模块各有自己的日志文件夹和运行总表一行；运行多个模块时另有一个“主控”日志。
#   - 每个模块读自己的设置（模块参数.json）：查询区域、发到飞书 等。
#
# 模块要提供（约定）：
#   模块名                          中文名，和文件名一样（“原名”，固定不变）；
#                                   卡片、Excel、日志里显示的名字用 模块参数.显示名(模块名)，小柒可以在窗口里改
#   默认参数                        可选，例如 {"区域": ["D区", "E区"]}
#   运行(页面, 记录, 参数) -> 结果    结果至少有 状态、数量、错误信息、错误列表
#   失败结果(错误, 开始时间, 参数)    还没开始查就失败时，给出一份“失败”结果
#   组成消息(结果, 日志文件夹名, 用时) -> (消息, 格式问题)
#       消息是文字；或者是 {"文字", "卡片" 或 "卡片们"（多张）, "附件"(Excel), "表们"[(表名, 列名, 行们)], "备注", "标题"}
#       消息里其他的键原样交给窗口，窗口认得的有：
#         "结论"（结果页最上面的一句话）、"提醒们"（橙框里的句子）、"要看数"（有几条要看，标签变 ⚠）、
#         "数量表们"（数量表样子）、"分组"（区域和单号样子）、"面单"（任务和面单样子）、"不发飞书"
#   网站 = "飞书"                    可选；不写就是 WMS。只有飞书类模块时，不打开 WMS、不检查 WMS 登录
#   需要选择 = True                  可选；运行中要弹窗让人勾选时，运行() 会多收到一个 选择 参数
import importlib
import time
from datetime import datetime

from 公共 import 模块参数, 查询范围, 防睡眠, 飞书
from 公共.wms import WMS首页, 打开WMS, 启动浏览器
from 公共.日志 import 运行记录
from 公共.错误 import 自动化错误, 归类, 程序出错, 立刻停下, 技术原文

成功状态 = ("成功", "无数据", "未运行")   # 未运行 = 查询范围一项都没勾，按小柒的意思不跑


def 载入模块(名):
    try:
        模块 = importlib.import_module(f"模块.{名}")
        return 模块, 模块参数.读取(名, getattr(模块, "默认参数", {})), None
    except Exception as e:
        错误 = 自动化错误(程序出错, f"模块文件“{名}.py”载入出错（英文技术原文写进了这次的日志）。")
        错误.技术原文 = 技术原文(e)
        return None, 模块参数.读取(名), 错误


def _失败(模块, 错误, 开始, 参数):
    if 模块 is None:
        return {"状态": "失败", "数量": None, "开始时间": 开始, "错误信息": 错误.一句话(), "错误列表": [错误]}
    return 模块.失败结果(错误, 开始, 参数)


def 运行模块们(名列表, 可见=False, 发送=True, 显示=True, 等待登录=None, 回报=None, 测试=None, 选择=None):
    """回报(事件, 内容)：窗口版用来显示进度。事件有 开始模块 / 模块完成（查完）/ 模块结果（整理好、发完飞书，给窗口显示的完整结果）。
    每个模块查完马上整理、发飞书、写日志，不等后面的模块（小柒 2026-10-24）。
    选择(清单)：窗口版用来弹出勾选窗口（只有 需要选择=True 的模块会用）。
    测试=True（或环境变量 仓库助手_测试=1）：发出去的卡片和文字标题前都加“【测试】”。
    Claude 自测、验证时必须用测试=True；只有小柒自己在窗口/菜单里运行时才发正式消息。"""
    import os
    if 测试 is None:
        测试 = os.environ.get("仓库助手_测试") == "1"
    from playwright.sync_api import sync_playwright
    from 公共 import 任务查询
    任务查询.新的一次运行()          # 查询间隔每次运行从 1 秒开始；这次运行里放慢了就一直保持（各模块共用）
    开始 = datetime.now()
    方式 = ("可见窗口" if 可见 else "后台") + ("，可发飞书" if 发送 else "，不发飞书")
    多个 = len(名列表) > 1
    主控 = 运行记录("主控", 方式 + "；模块：" + "、".join(map(模块参数.显示名, 名列表)), 测试=测试) if 多个 else None
    运行记录.本次主控, 运行记录.正在 = 主控, None       # 运行中关窗口时，窗口用它们补“被中止”
    清单 = []   # 每项：[名, 模块, 参数, 记录, 结果, 开始时间]

    def 打印(文字):
        if 显示:
            print(文字, flush=True)

    def 通知(事件, 内容):
        if 回报:
            try:
                回报(事件, 内容)
            except Exception:
                pass

    # —— 每个模块查完马上收尾：组成消息、按设置发飞书、写日志，然后告诉窗口（小柒 2026-10-24：不等后面的模块）——
    消息们 = []

    def 收尾(名, 模块, 参数, 记录, 结果, 模块开始):
        try:
            项 = _收尾(名, 模块, 参数, 记录, 结果, 模块开始)
        except Exception as 意外:   # 收尾本身出错也要有一份结果，不能让窗口一直等
            记录.写(f"收尾出错：{type(意外).__name__}: {意外}")
            项 = {"模块": 名, "显示名": 模块参数.显示名(名), "状态": 结果["状态"],
                 "文字": f"【{模块参数.显示名(名)}】{结果['状态']}\n{结果.get('错误信息', '')}", "附件": None,
                 "表们": [], "备注": [], "标题": "", "分组": None, "卡片们": [], "飞书": ("未发送", f"收尾出错：{意外}"),
                 "日志文件夹": str(记录.文件夹), "数量": 结果.get("数量"), "时间": 结果.get("开始时间"), "错误们": []}
        消息们.append(项)
        通知("模块结果", 项)

    def _收尾(名, 模块, 参数, 记录, 结果, 模块开始):
        用时 = (datetime.now() - 模块开始).total_seconds()
        卡片们, 附件, 表们, 备注, 标题, 分组 = [], None, [], [], "", None
        try:
            if 模块 is None:
                raise ValueError("模块没有载入")
            if 结果["状态"] == "未运行":   # 查询范围一项都没勾：不跑，也不发飞书
                消息, 格式问题 = {"文字": f"【{模块参数.显示名(名)}】没有勾选查询范围，这次没有运行",
                              "结论": "没有勾选查询范围，这次没有运行",
                              "提醒们": ["要跑这个模块：在工作台点它，在右边“查询范围”里勾选仓库或区。"],
                              "不发飞书": True}, ""
            else:
                消息, 格式问题 = 模块.组成消息(结果, 记录.文件夹名, 用时=用时)
            if 格式问题:
                记录.写(f"消息格式：{格式问题}")
        except Exception as e:
            记录.写(f"组成消息出错：{type(e).__name__}: {e}")
            消息 = f"【{模块参数.显示名(名)}】{结果['状态']}\n{结果.get('错误信息', '')}"
        if isinstance(消息, dict):
            卡片们 = 消息.get("卡片们") or ([消息["卡片"]] if 消息.get("卡片") else [])
            附件, 文字 = 消息.get("附件"), 消息.get("文字", "")
            表们, 备注, 标题 = 消息.get("表们", []), 消息.get("备注", []), 消息.get("标题", "")
            分组 = 消息.get("分组")
        else:
            文字 = 消息
        if 测试:   # 自测、验证时发的消息一律标【测试】，和小柒自己运行的正式结果区分开
            for 卡 in 卡片们:
                卡["header"]["title"]["content"] = "【测试】" + 卡["header"]["title"]["content"]
            文字 = "【测试】" + 文字

        if 结果["状态"] == "未运行":
            发送状态, 发送说明 = "未发送", "没选查询范围，没有运行"
        elif not 发送:
            发送状态, 发送说明 = "未发送", "本次选择不发送"
        elif not getattr(模块, "可发飞书", True):
            发送状态, 发送说明 = "未发送", "这个模块只在窗口里看，不发飞书"
        elif not 参数.get("发到飞书", True):
            发送状态, 发送说明 = "未发送", "这个模块设置为不发飞书"
        elif not 飞书.可以发送():
            发送状态, 发送说明 = "未发送", "还没设置好飞书（点“设置飞书”）"
        else:
            if any(项["飞书"][0] != "未发送" for 项 in 消息们):
                time.sleep(1)   # 飞书机器人每秒最多 5 条，留点间隔
            记录.写("发送飞书 ……")
            记录.保存发送内容(文字, "（准备发送）" + (f"，{len(卡片们)} 张卡片" if 卡片们 else ""))
            if len(卡片们) > 1:
                记录.写(f"    内容较多，拆成 {len(卡片们)} 张卡片发送（每张不超过 18 KB，不丢内容）")
            发送状态, 发送说明 = 飞书.发送全部(
                卡片们, 文字, 每张=lambda 张, 共, 状, 说: 记录.写(f"    第 {张}/{共} 张：{状}（{说}）"))
        记录.保存发送内容(文字, f"{发送状态}：{发送说明}")
        记录.写(f"飞书：{发送状态}（{发送说明}）")
        摘要 = 结果.get("错误信息", "")
        if 发送状态 in ("失败", "未知"):
            摘要 = (摘要 + "；" if 摘要 else "") + f"飞书{发送状态}：{发送说明}"
        记录.结束(结果["状态"], 结果.get("数量"), 摘要)
        项 = {"模块": 名, "显示名": 模块参数.显示名(名), "状态": 结果["状态"], "文字": 文字, "附件": 附件,
             "表们": 表们, "备注": 备注, "标题": 标题, "分组": 分组, "卡片们": 卡片们,
             "飞书": (发送状态, 发送说明), "日志文件夹": str(记录.文件夹),
             "数量": 结果.get("数量"), "时间": 结果.get("开始时间"),
             "错误们": [{"步骤": getattr(e, "步骤", ""), "原因": f"{getattr(e, '类型', '出错')}：{getattr(e, '原因', e)}",
                       "建议": getattr(e, "建议", "")} for e in 结果.get("错误列表", [])]}
        if isinstance(消息, dict):   # 模块给窗口的其他内容（例如“面单”“不发飞书”）原样带上，不能漏
            for 键, 值 in 消息.items():
                项.setdefault(键, 值)
        return 项

    预载 = {名: 载入模块(名) for 名 in 名列表}
    不跑 = {名 for 名, (模块, 参数, _) in 预载.items() if 模块 is not None and 查询范围.没选(参数)}
    要跑 = [x for 名, x in 预载.items() if 名 not in 不跑]
    需要WMS = any(模块 is None or getattr(模块, "网站", "WMS") == "WMS" for 模块, _, _ in 要跑)
    不睡 = 防睡眠.开始() if 要跑 else None   # 运行期间别让电脑自动睡眠（体检 2026-10-28），最后的 finally 里一定恢复
    try:
        with sync_playwright() as p:
            浏览器 = 页面 = None
            打开失败 = None
            首个记录 = 主控 or 运行记录(名列表[0], 方式, 测试=测试)
            if not 多个:
                运行记录.正在 = 首个记录
            if 不睡 is not None:
                首个记录.写("已请 Windows 在运行期间不要自动睡眠、不要自动关屏（合盖仍会睡）" if 不睡
                          else "没能请 Windows 保持不睡眠（运行照常，请别让电脑睡着）")
            try:
                if not 要跑:
                    首个记录.写("选的模块都没有勾选查询范围，不打开浏览器")
                elif 需要WMS:
                    with 首个记录.步骤("打开 WMS 并检查登录"):
                        浏览器, 页面 = 打开WMS(p, 可见=可见, 记录=首个记录, 等待登录=等待登录)
                else:
                    with 首个记录.步骤("打开自动化专用 Chrome"):
                        浏览器, 页面 = 启动浏览器(p, 可见)
                        首个记录.页面 = 页面
            except 自动化错误 as e:
                打开失败 = e
            停下错误 = None
            for 序号, 名 in enumerate(名列表, 1):
                打印(f"\n▶ [{序号}/{len(名列表)}] {模块参数.显示名(名)} ……")
                通知("开始模块", (序号, len(名列表), 名))
                模块, 参数, 载入错误 = 预载[名]
                记录 = 首个记录 if not 多个 else 运行记录(名, 方式, 测试=测试)
                运行记录.正在 = 记录
                模块开始 = datetime.now()
                if 页面 is not None:
                    记录.页面 = 页面
                if 参数.get("查询范围"):
                    记录.写(f"查询范围：{'、'.join(参数['查询范围'])}")
                if 名 in 不跑:
                    记录.写("查询范围一项都没勾：按设置不跑这个模块（小柒 2026-10-24）。")
                    结果 = {"状态": "未运行", "数量": None, "开始时间": 模块开始, "错误信息": "", "错误列表": []}
                elif 载入错误 or 打开失败 or 停下错误:
                    if 载入错误 or 打开失败:
                        错误 = 载入错误 or 打开失败
                    else:   # 前面的模块遇到 WMS 提示：后面的模块都不跑（体检 2026-10-28）
                        错误 = 自动化错误(停下错误.类型, f"前面的模块遇到 {停下错误.原因}，已全部停下，这个模块没有运行。")
                        错误.步骤 = "（没有运行）"
                    记录.写(f"没有运行：{错误.原因}")
                    if getattr(错误, "技术原文", ""):
                        记录.写(f"    技术原文：{错误.技术原文}")
                    结果 = _失败(模块, 错误, 模块开始, 参数)
                else:
                    try:
                        if 多个 and getattr(模块, "网站", "WMS") == "WMS":
                            with 记录.步骤("回到 WMS 首页并刷新"):
                                页面.goto(WMS首页)
                                页面.reload()
                                页面.locator(".el-menu").first.wait_for(timeout=15000)
                        if getattr(模块, "需要选择", False):
                            结果 = 模块.运行(页面, 记录, 参数, 选择=选择)
                        else:
                            结果 = 模块.运行(页面, 记录, 参数)
                    except 自动化错误 as e:
                        结果 = _失败(模块, e, 模块开始, 参数)
                    except Exception as 原始:   # 模块里没想到的错误，也要留下现场
                        记录.保存现场(原始)
                        e = 归类(原始)
                        记录.写(f"出错：{e.类型}：{e.原因}")
                        记录.写(f"    技术原文：{技术原文(原始)}")
                        e.步骤 = e.步骤 or "（不在任何步骤里）"
                        结果 = _失败(模块, e, 模块开始, 参数)
                if 停下错误 is None:
                    停下错误 = next((e for e in 结果.get("错误列表", []) if getattr(e, "类型", None) in 立刻停下), None)
                    if 停下错误 is not None:
                        记录.写("WMS 弹出了提示，按规矩整次运行立刻停下，后面的模块不再运行")
                打印(f"  {结果['状态']}" + (f"，数量 {结果['数量']}" if 结果.get("数量") is not None else ""))
                通知("模块完成", (名, 结果))
                清单.append([名, 模块, 参数, 记录, 结果, 模块开始])
                收尾(名, 模块, 参数, 记录, 结果, 模块开始)
                运行记录.正在 = None
            if 浏览器:
                浏览器.close()
    except Exception as 原始:   # 浏览器本身崩溃之类
        e = 归类(原始)
        (主控 or 运行记录("主控", 方式, 测试=测试)).保存现场(原始)
        已跑 = {项[0] for 项 in 清单}
        for 名 in 名列表:
            if 名 not in 已跑:
                模块, 参数, _ = 载入模块(名)
                清单.append([名, 模块, 参数, 运行记录(名, 方式, 测试=测试), _失败(模块, e, datetime.now(), 参数), datetime.now()])
                收尾(*清单[-1])
    finally:
        运行记录.正在 = None
        if 不睡 is not None:
            防睡眠.恢复()


    if 主控:
        for 项 in 消息们:
            主控.写(f"{项['显示名']}：{项['状态']}，飞书 {项['飞书'][0]}，日志 {项['日志文件夹']}")
        有问题 = [项["显示名"] for 项 in 消息们 if 项["状态"] not in 成功状态]
        飞书问题 = [项["显示名"] for 项 in 消息们 if 项["飞书"][0] in ("失败", "未知")]
        摘要 = "；".join(x for x in (("有问题的模块：" + "、".join(有问题)) if 有问题 else "",
                                    ("飞书没发成功：" + "、".join(飞书问题)) if 飞书问题 else "") if x)
        主控.结束("成功" if not 有问题 else "有问题", None, 摘要)

    for 项 in 消息们:
        打印("\n" + "=" * 40 + "\n" + 项["文字"] + "\n" + "=" * 40)
        打印(f"飞书：{项['飞书'][0]}（{项['飞书'][1]}）" + (f"    Excel：{项['附件']}" if 项["附件"] else ""))
    打印(f"总用时：{(datetime.now() - 开始).total_seconds():.0f} 秒    日志：{(主控 or 清单[0][3]).文件夹}")
    return {"结果们": [项[4] for 项 in 清单], "消息们": 消息们,
            "日志文件夹": str((主控 or 清单[0][3]).文件夹)}

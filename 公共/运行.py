# 职责：按顺序运行一个或几个模块（菜单和单独运行都用它）。
# 输入：模块名列表（按运行顺序）、是否显示浏览器、是否发飞书。
# 输出：每个模块的结果列表；飞书只发一条（多个模块时是汇总，每个模块一段，用各自的格式）。
# 规则：
#   - WMS 只打开一次，各模块依次使用；每个模块开始前回到首页并刷新，互不影响。
#   - 一个模块失败不影响下一个。
#   - 每个模块各有自己的日志文件夹和运行总表一行；另有一个“主控”日志记录整体情况。
#
# 模块要提供（约定）：
#   模块名                      中文名，和文件名一样
#   运行(页面, 记录) -> 结果     结果至少有 状态、数量、错误信息、错误列表
#   失败结果(错误, 开始时间)     还没开始查就失败时，给出一份“失败”结果
#   组成消息(结果, 日志文件夹名, 用时) -> (消息, 格式问题)
#   保存最近结果(结果)          可选，给“设置消息格式”预览用
import importlib
from datetime import datetime

from 公共 import 飞书
from 公共.wms import WMS首页, 打开WMS
from 公共.日志 import 运行记录
from 公共.错误 import 自动化错误, 归类, 程序出错

成功状态 = ("成功", "无数据")


def 载入模块(名):
    try:
        return importlib.import_module(f"模块.{名}"), None
    except Exception as e:
        return None, 自动化错误(程序出错, f"模块文件“{名}.py”载入出错：{type(e).__name__}: {e}")


def 运行模块们(名列表, 可见=False, 发送=True, 显示=True):
    from playwright.sync_api import sync_playwright
    开始 = datetime.now()
    方式 = ("可见窗口" if 可见 else "后台") + ("，发飞书" if 发送 else "，不发飞书")
    多个 = len(名列表) > 1
    主控 = 运行记录("主控", 方式 + "；模块：" + "、".join(名列表)) if 多个 else None
    清单 = []   # 每项：[名, 模块, 记录, 结果, 开始时间]

    def 打印(文字):
        if 显示:
            print(文字, flush=True)

    try:
        with sync_playwright() as p:
            浏览器 = 页面 = None
            打开失败 = None
            首个记录 = 主控 or 运行记录(名列表[0], 方式)
            try:
                with 首个记录.步骤("打开 WMS 并检查登录"):
                    浏览器, 页面 = 打开WMS(p, 可见=可见, 记录=首个记录)
            except 自动化错误 as e:
                打开失败 = e
            for 序号, 名 in enumerate(名列表, 1):
                打印(f"\n▶ [{序号}/{len(名列表)}] {名} ……")
                模块, 载入错误 = 载入模块(名)
                记录 = 首个记录 if (not 多个) else 运行记录(名, 方式)
                模块开始 = datetime.now()
                if 页面 is not None:
                    记录.页面 = 页面
                if 载入错误 or 打开失败:
                    错误 = 载入错误 or 打开失败
                    记录.写(f"没有运行：{错误.原因}")
                    结果 = 模块.失败结果(错误, 模块开始) if 模块 else _通用失败(错误)
                else:
                    try:
                        if 多个:
                            with 记录.步骤("回到 WMS 首页并刷新"):
                                页面.goto(WMS首页)
                                页面.reload()
                                页面.locator(".el-menu").first.wait_for(timeout=15000)
                        结果 = 模块.运行(页面, 记录)
                    except 自动化错误 as e:
                        结果 = 模块.失败结果(e, 模块开始)
                    except Exception as 原始:   # 模块里没想到的错误，也要留下现场
                        记录.保存现场(原始)
                        e = 归类(原始)
                        e.步骤 = e.步骤 or "（不在任何步骤里）"
                        结果 = 模块.失败结果(e, 模块开始)
                if 模块 and hasattr(模块, "保存最近结果"):
                    模块.保存最近结果(结果)
                打印(f"  {结果['状态']}" + (f"，数量 {结果['数量']}" if 结果.get("数量") is not None else ""))
                清单.append([名, 模块, 记录, 结果, 模块开始])
            if 浏览器:
                浏览器.close()
    except Exception as 原始:   # 浏览器本身崩溃之类
        e = 归类(原始)
        (主控 or 运行记录("主控", 方式)).保存现场(原始)
        已跑 = {项[0] for 项 in 清单}
        for 名 in 名列表:
            if 名 not in 已跑:
                模块, _ = 载入模块(名)
                结果 = 模块.失败结果(e, datetime.now()) if 模块 else _通用失败(e)
                清单.append([名, 模块, 运行记录(名, 方式), 结果, datetime.now()])

    # —— 组成消息 ——
    段落 = []
    for 名, 模块, 记录, 结果, 模块开始 in 清单:
        用时 = (datetime.now() - 模块开始).total_seconds()
        if 模块:
            消息, 格式问题 = 模块.组成消息(结果, 记录.文件夹名, 用时=用时)
            if 格式问题:
                记录.写(f"消息格式：{格式问题}")
        else:
            消息 = f"【{名}】没有运行\n{结果['错误信息']}"
        段落.append(消息)
    if 多个:
        好 = sum(1 for 项 in 清单 if 项[3]["状态"] in 成功状态)
        标题 = f"【仓库助手 汇总】{开始:%Y-%m-%d %H:%M}  共 {len(清单)} 个模块：{好} 个正常"
        if 好 < len(清单):
            标题 += f"，{len(清单) - 好} 个有问题 ⚠"
        总消息 = 标题 + "\n\n" + "\n\n──────────\n".join(段落)
        if 主控:
            总消息 += f"\n\n日志：{主控.文件夹名}"
    else:
        总消息 = 段落[0]

    # —— 发送（只发一条） ——
    if 发送 and 飞书.可以发送():
        发送状态, 发送说明 = 飞书.发送(总消息)
    else:
        发送状态, 发送说明 = "未发送", ("本次选择不发送" if not 发送 else "还没设置好飞书（双击 设置飞书.bat）")

    # —— 写日志、运行总表 ——
    for 名, 模块, 记录, 结果, _ in 清单:
        记录.保存发送内容(总消息, f"{发送状态}：{发送说明}")
        记录.写(f"飞书：{发送状态}（{发送说明}）")
        摘要 = 结果.get("错误信息", "")
        if 发送状态 in ("失败", "未知"):
            摘要 = (摘要 + "；" if 摘要 else "") + f"飞书{发送状态}：{发送说明}"
        记录.结束(结果["状态"], 结果.get("数量"), 摘要)
    if 主控:
        for 名, _, 记录, 结果, _ in 清单:
            主控.写(f"{名}：{结果['状态']}，日志 {记录.文件夹名}")
        有问题 = [项[0] for 项 in 清单 if 项[3]["状态"] not in 成功状态]
        摘要 = ("有问题的模块：" + "、".join(有问题)) if 有问题 else ""
        if 发送状态 in ("失败", "未知"):
            摘要 = (摘要 + "；" if 摘要 else "") + f"飞书{发送状态}：{发送说明}"
        主控.结束("成功" if not 有问题 else "有问题", None, 摘要)

    打印("\n" + "=" * 40)
    打印(总消息)
    打印("=" * 40)
    打印(f"飞书：{发送状态}（{发送说明}）    总用时：{(datetime.now() - 开始).total_seconds():.0f} 秒")
    打印(f"日志：{(主控 or 清单[0][2]).文件夹}")
    return [项[3] for 项 in 清单]


def _通用失败(错误):
    return {"状态": "失败", "数量": None, "区域列表": [], "开始时间": datetime.now(),
            "错误信息": 错误.一句话(), "错误列表": [错误]}

# 职责：查询范围的规则（待审核、待拣货、待增值、无任务包裹共用；小柒 2026-10-24 确认）。
#   仓库：瑞江仓库 = D区 + E区；松户仓库 = A区 + C区 + F区。B区 是测试区，不属于任何仓库。
#   可以勾仓库，也可以勾单独的区；每个勾选项单独一张表、一张飞书卡片。
#   勾了仓库，它包含的区就不能再单独勾（界面上收起；旧设置里有的话按规则去掉，并在结果里说一句）。
#   两个仓库可以同时勾；单独勾 D区 和 E区 时是两张单独的表，不会自动合成瑞江仓库。
#   至少要勾一项。
# 界面显示、保存设置、运行时用的参数，都经过这里的 整理()，三处一定一致。
from 公共 import 模块参数

仓库 = {"瑞江仓库": ["D区", "E区"], "松户仓库": ["A区", "C区", "F区"]}
测试区 = {"B区": "测试区"}


def 区域们():
    """单独的区（来自 WMS 的“所属区域”下拉，运行待处理模块时自动更新；没有时用 A～F）。"""
    return list(模块参数.区域选项())


def 选项():
    return list(仓库) + 区域们()


def 说明(名):
    """勾选框上的字：瑞江仓库（D区 + E区）、B区（测试区）、A区。"""
    if 名 in 仓库:
        return f"{名}（{' + '.join(仓库[名])}）"
    if 名 in 测试区:
        return f"{名}（{测试区[名]}）"
    return 名


def 包含它的仓库(区, 选择):
    return next((仓 for 仓 in 仓库 if 仓 in 选择 and 区 in 仓库[仓]), None)


def 整理(选择):
    """按规则整理勾选。返回 (整理后的列表, 去掉的说明列表)。顺序固定：先仓库，再按区的顺序。"""
    选择 = list(选择 or [])
    有效 = set(选项())
    结果 = [仓 for 仓 in 仓库 if 仓 in 选择]
    去掉 = []
    for 名 in dict.fromkeys(选择):
        if 名 not in 有效:
            去掉.append(f"没有“{名}”这个选项")
        elif 名 not in 仓库 and (仓 := 包含它的仓库(名, 结果)):
            去掉.append(f"{名} 已经包含在{仓}里")
    结果 += [区 for 区 in 区域们() if 区 in 选择 and not 包含它的仓库(区, 结果)]
    return 结果, 去掉


def 展开(选择):
    """["瑞江仓库", "B区"] → [("瑞江仓库", ["D区", "E区"]), ("B区", ["B区"])]（先整理）。"""
    return [(名, 仓库.get(名, [名])) for 名 in 整理(选择)[0]]


def 要查的区(选择):
    """去重后的区，按表的顺序：["瑞江仓库", "B区"] → ["D区", "E区", "B区"]。"""
    return list(dict.fromkeys(区 for _, 区们 in 展开(选择) for 区 in 区们))


def 从旧区域(区们):
    """无任务包裹以前存的是区的列表（“区域”）。整仓都勾了的换成仓库，其余照旧——查的区完全一样。"""
    区们 = list(区们 or [])
    选择 = [仓 for 仓, 含 in 仓库.items() if all(区 in 区们 for 区 in 含)]
    选择 += [区 for 区 in 区们 if not 包含它的仓库(区, 选择)]
    return 整理(选择)[0]


def 迁移旧设置():
    """把 模块参数.json 里还用旧“区域”的模块改成“查询范围”（只改一次；查的区不变）。返回改了哪些模块。"""
    改了 = []
    if not any("区域" in 参数 and "查询范围" not in 参数 for 参数 in 模块参数._读全部().get("模块", {}).values()):
        return 改了

    def 动作(数据):
        for 名, 参数 in 数据.get("模块", {}).items():
            if "区域" in 参数 and "查询范围" not in 参数:
                参数["查询范围"] = 从旧区域(参数.pop("区域"))
                改了.append(名)
    模块参数._改(动作)
    return 改了

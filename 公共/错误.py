def WMS提示错误(原文):
    """页面上读到 WMS 自己弹出的提示框文字 → 对应的错误（照原文报出）。"""
    原文 = " ".join(str(原文).split())[:120]
    类型 = 账号被挤 if any(词 in 原文 for 词 in _账号词) else WMS提示
    return 自动化错误(类型, f"WMS 弹出提示：“{原文}”")


def 是浏览器被关(异常):
    """Playwright 在浏览器（或它的窗口）已经关掉时报 TargetClosedError / “…has been closed”。"""
    文字 = f"{type(异常).__name__}: {异常}"
    return "TargetClosed" in 文字 or "has been closed" in 文字


class 自动化错误(Exception):
    def __init__(self, 类型, 原因):
        super().__init__(原因)
        self.类型 = 类型
        self.原因 = 原因
        self.建议 = 建议表.get(类型, 建议表[程序出错])
        self.步骤 = ""   # 出错的步骤，由日志记录器填上

    def 一句话(self, 模块名=""):
        """统一格式：模块 → 步骤 → 原因 → 建议。模块用窗口里改过的名字。"""
        if 模块名:
            from 公共.模块参数 import 显示名
            模块名 = 显示名(模块名)
        部分 = [p for p in (模块名, self.步骤) if p]
        return " → ".join(部分 + [f"{self.类型}：{self.原因}", f"建议：{self.建议}"])


def 归类(异常):
    """把 Python / Playwright 的原始报错归到上面几类。"""
    if isinstance(异常, 自动化错误):
        return 异常
    文字 = f"{type(异常).__name__}: {异常}"
    首行 = 文字.splitlines()[0][:200]
    if 是浏览器被关(异常):
        return 自动化错误(浏览器被关, "运行用的 Chrome 窗口被关闭了（或浏览器意外退出），程序没法继续。")
    if "net::" in 文字 or "ERR_" in 文字:
        return 自动化错误(网络超时, "网络连接出错：" + 首行)
    if "Timeout" in type(异常).__name__ or "Timeout" in 文字[:80]:
        if "locator" in 文字 or "waiting for" in 文字 and "event" not in 文字:
            return 自动化错误(页面改版, "等了很久也找不到要点的按钮或输入框：" + 首行)
        return 自动化错误(网络超时, "等待超时：" + 首行)
    return 自动化错误(程序出错, 首行)

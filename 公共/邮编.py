@lru_cache(maxsize=1)
def _数据():
    """读官方数据 → (县 → 市区町村 → [(町域, 邮编7位)]，邮编 → [(县, 市, 町)])。"""
    if not 数据文件.exists():
        raise FileNotFoundError(f"没有邮编数据文件：{数据文件}")
    县市 = {}
    按邮编 = {}
    with open(数据文件, encoding="utf-8", newline="") as f:
        for 行 in csv.reader(f):
            邮编, 县, 市, 町 = 行[2], 行[6], 行[7], 行[8]
            县市.setdefault(县, {}).setdefault(市, []).append((町, 邮编))
            按邮编.setdefault(邮编, []).append((县, 市, 町))
    return 县市, 按邮编


def 更新数据():
    """从日本邮政官网重新下载 utf_ken_all.zip，检查条数正常后替换本机数据。返回 (成功?, 说明)。
    只在小柒点窗口里的“更新邮编数据”时运行（需要联网）。"""
    import io
    import urllib.request
    import zipfile
    from urllib.parse import urljoin
    头 = {"User-Agent": "Mozilla/5.0"}
    try:
        页 = urllib.request.urlopen(urllib.request.Request(下载页, headers=头), timeout=60).read().decode("utf-8", "ignore")
        链接 = [l for l in re.findall(r'href="([^"]*\.zip)"', 页) if l.endswith("utf_ken_all.zip")]
        if not 链接:
            return False, "官网页面上找不到 utf_ken_all.zip 的下载链接（官网可能改版了），本机数据没有动。"
        数据 = urllib.request.urlopen(urllib.request.Request(urljoin(下载页, 链接[0]), headers=头), timeout=120).read()
        with zipfile.ZipFile(io.BytesIO(数据)) as 包:
            名 = next(n for n in 包.namelist() if n.lower().endswith(".csv"))
            内容 = 包.read(名)
        条数 = 内容.count(b"\n")
        if 条数 < 100000:
            return False, f"下载的数据只有 {条数} 条，看起来不对，本机数据没有动。"
        临时 = 数据文件.with_suffix(".新")
        临时.write_bytes(内容)
        临时.replace(数据文件)
        _数据.cache_clear()
        return True, f"已更新：{条数} 条（日本邮政官网最新版）。"
    except Exception as e:
        return False, f"更新没有成功（{type(e).__name__}: {str(e)[:120]}），本机数据没有动。"



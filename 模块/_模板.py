# 职责：新模块的骨架。用法：复制这个文件 → 改名（去掉开头的下划线）→ 按你的流程改“运行”和“组成消息”。
#
# ⚠ 文件名以 _ 开头：程序不会把它当成模块加载，工作台也不会显示它。
#   复制成 我的模块.py 之后才会出现在工作台最后一行（默认“关”，核对通过再打开）。
#
# ── 一个模块必须有这 5 样（前 3 个是函数，缺一个程序会直接说缺哪个，不会等跑完才报“程序本身出错”）──
#   模块名            中文名，和文件名一样（这是“原名”，固定不变；卡片上显示的名字可以在窗口里改）
#   默认参数          例如 {"查询范围": ["瑞江仓库"], "发到飞书": True}
#   运行(页面, 记录, 参数)          → 结果字典
#   失败结果(错误, 开始时间, 参数)   → 结果字典（还没开始查就失败时用）
#   组成消息(结果, 文件夹名, 用时)   → (消息, 格式问题)
#
# ── 还可以写这几样（不写就用默认）──
#   说明 = "一句话"       工作台卡片上写的用途
#   网站 = "飞书"         不打开 WMS（飞书类模块）
#   需要选择 = True       运行中弹窗让人勾选；这时 运行() 会多收到一个 选择 参数
#   可发飞书 = False      这个模块只在窗口里看
#
# ── 结果字典必须有这 5 个键 ──
#   状态       "成功" / "无数据" / "不完整" / "失败" / "未运行"
#   数量       int 或 None。**失败时必须是 None，绝不能写 0**（0 的意思是“查到了，确实没有”）
#   开始时间   datetime
#   错误信息   一句话（显示在界面上）
#   错误列表   [自动化错误, …]（“哪一步 / 原因 / 怎么办”由 公共\运行.py 自动展开，不用自己拼）
#
# ── 组成消息 返回的 dict ──
#   "文字"      飞书纯文本（必填）
#   "结论"      结果页最上面那句话
#   "提醒们"    ["橙色提醒一句话", …]
#   "要看数"    有几条要看（左边模块列表标 ⚠）
#   "附件"      Excel 路径
#   内容三选一（都放不下时先问小柒，不要另造样子）：
#     "数量表们"  [("表名", 列名们, 行们), …]
#     "分组"      {"总览": (列名, 行们), "明细": [(区名, 单号们, 复制文字), …]}
#     "面单"      [{"序", "类型", "单号", "标题", "段们", …}, …]
#
# ── 查询的三条老规矩（代码各写各的，但规矩要守）──
#   1. 点“查询”后等页面自己的接口返回，最多等 30 秒（别无限等，也别只 sleep 几秒就往下读）
#   2. 读完必须核对：接口里的条件对不对 + 页面上“共 N 条记录”和读到的数对不对。对不上就报错，不猜
#   3. 查不到 ≠ 0。读不到总数就抛 自动化错误，绝不返回 0 冒充“没有”
import sys
from datetime import datetime
from pathlib import Path

根目录 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(根目录))
from 公共 import 查询范围, 表格  # noqa: E402
from 公共.错误 import 自动化错误, 程序出错, 设置有误  # noqa: E402
from 公共.模块参数 import 显示名  # noqa: E402
from 公共.wms import 进入页面  # noqa: E402  按左侧菜单进页面（会等页面自己的查询接口返回）

模块名 = "_模板"
默认参数 = {"查询范围": ["瑞江仓库"], "发到飞书": True}
说明 = "（一句话说明这个模块查什么）"
已写流程 = False          # ← 改完 运行() 之后把它改成 True；没改之前运行会直接告诉你“这还是模板”


def 运行(页面, 记录, 参数=None):
    """页面已经登录好。返回结果字典。
    规则：查不到就抛 自动化错误，绝不返回 0 冒充；一个区失败不影响另一个区。"""
    参数 = 参数 or 默认参数
    开始时间 = datetime.now()
    if not 已写流程:
        raise 自动化错误(程序出错, "这个模块还是模板，还没写查询流程（照 _模板.py 开头的注释改 运行()，"
                                 "改完把 已写流程 改成 True）。")
    要查 = 查询范围.要查的区(参数.get("查询范围"))   # 瑞江仓库 = D+E；松户仓库 = A+C+F；也可以直接勾某个区
    if not 要查:
        return 失败结果(自动化错误(设置有误, "查询范围是空的，不能查。"), 开始时间, 参数)

    # ── 1. 进页面：每一步都用 with 记录.步骤(...)，出错时日志里就有“第几步、卡在哪” ──
    with 记录.步骤("进入 仓库管理 → 数据管理 → （你的页面）"):
        进入页面(页面, ["仓库管理", "数据管理", "（你的页面）"], 等待接口="（页面查询接口里的那段文字）")

    # ── 2. 选条件：下拉用 公共\表单.下拉选择(页面, "区域", 区)；日期用 清空日期(页面, "签收时间") ──
    # ── 3. 查一个区：点“查询”→ 等接口返回 → 核对条件 → 读数字或读单号（见本文件开头第 1~3 条规矩）──
    错误们, 各区的数 = [], {}
    for 区 in 要查:
        with 记录.步骤(f"查询 {区}"):
            # ↓↓↓ 你的流程写在这里 ↓↓↓
            各区的数[区] = 0
            记录.写(f"    {区}：0")
            # ↑↑↑ 你的流程写在这里 ↑↑↑

    # ── 4. 定状态 ──
    #   全是 0            → "无数据"（查到了，确实没有）
    #   都对上            → "成功"
    #   有的区没查到/对不上 → "不完整"（合计写 “N+”，不是 N）
    #   全没查到          → "失败"（数量必须是 None）
    合计 = sum(各区的数.values())
    return {"状态": "无数据" if 合计 == 0 else "成功", "数量": 合计, "开始时间": 开始时间,
            "错误信息": "；".join(e.一句话(模块名) for e in 错误们), "错误列表": 错误们,
            "各区": 各区的数}


def 失败结果(e, 开始时间, 参数=None):
    """还没开始查就失败了（没登录、查询范围没选、模块载入出错……）。数量必须是 None。"""
    return {"状态": "失败", "数量": None, "开始时间": 开始时间,
            "错误信息": e.一句话(模块名), "错误列表": [e]}


def 组成消息(结果, 文件夹名, 用时=None):
    """把结果变成：飞书文字 + 卡片 + 结果页内容。返回 (消息字典, 格式问题)；格式没问题就返回 ""。"""
    名 = 显示名(模块名)          # 窗口里改过的名字；卡片、Excel、复制出来的文字都要用它
    时间 = 结果["开始时间"]
    标题 = f"{名}（截至 {时间:%m/%d %H:%M}）"

    列名 = ["区域", "数量"]
    行们 = [[区, 数] for 区, 数 in 结果.get("各区", {}).items()]
    行们.append(["**合计**", f"**{结果.get('数量') or 0}**"])     # 合计行用 ** 包起来：会加粗

    文字 = 标题 + "\n\n" + 表格.文字表格(列名, 行们)
    消息 = {"文字": 文字, "标题": 标题, "结论": f"共 {结果.get('数量') or 0} 个",
            "表们": [("各区域数量", 列名, 行们)], "备注": []}
    return 消息, ""

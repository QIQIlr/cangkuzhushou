def 读品名表(文件=品名表文件):
    """返回 [(关键词小写, 日语品名)]，长的关键词排在前面。读不到返回 None（不影响其他内容）。"""
    try:
        文字 = Path(文件).read_text(encoding="utf-8-sig")
    except Exception:
        return None
    表 = []
    for 行 in 文字.splitlines():
        s = 行.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        品名, 右 = (x.strip() for x in s.split("=", 1))
        表 += [(w.strip().lower(), 品名) for w in re.split(r"[、,，]", 右) if w.strip()]
    return sorted(表, key=lambda x: -len(x[0]))


def 品名参考(内容物, 表):
    """内容物里出现的关键词 → 日语品名（去重，按出现先后）。没有对上返回 None。"""
    if not 表 or not 内容物 or 内容物.startswith("（"):
        return None
    文 = 内容物.lower()
    占, 找到 = [False] * len(文), []
    for 词, 品名 in 表:          # 长词优先，已经被长词占住的位置不再算
        起 = 文.find(词)
        while 起 >= 0:
            if not any(占[起:起 + len(词)]):
                for i in range(起, 起 + len(词)):
                    占[i] = True
                找到.append((起, 品名))
            起 = 文.find(词, 起 + 1)
    结果 = []
    for _, 品名 in sorted(找到):
        if 品名 not in 结果:
            结果.append(品名)
    return "、".join(结果) if 结果 else None


# ---------------- 标题 ----------------
def 解析标题(标题):
    """标题 → {状态, 类型, 转运单号, 会员码, 重量, 位置}；读不到的项是 None。"""
    m = re.match(r"^\s*((?:[（(][^）)]*[）)]\s*)+)", 标题)
    状态 = m[1].strip() if m else ""
    类 = re.search(r"【([^】]+)】", 标题)
    类型 = 类[1].strip() if 类 else ""
    主体 = 标题[类.end():] if 类 else 标题[len(m[0]) if m else 0:]
    单号 = re.search(r"(?<!\d)\d{6}-\d{6}(?!\d)", 主体)
    会员 = re.search(r"(?<![\dA-Za-z])\d{7}(?!\d)", 主体)
    重量 = re.search(r"(?<![\w.])(\d+(?:\.\d+)?)\s?(kg|KG|g|G)(?![A-Za-z])", 主体)
    区 = re.search(r"(?<![A-Za-z])([A-Z])区", 主体)
    货架 = re.search(r"(?<![A-Za-z0-9])[A-Z]\d{1,4}#\d{1,2}-\d{1,2}", 主体)
    位置 = None
    if 货架:
        位置 = (f"{区[0]} " if 区 else "") + 货架[0]
    return {"状态": 状态, "类型": 类型, "转运单号": 单号[0] if 单号 else None, "会员码": 会员[0] if 会员 else None,
            "重量": 重量[0].replace(" ", "") if 重量 else None, "位置": 位置,
            "区不一致": bool(区 and 货架 and 区[1] != 货架[0][0])}


# ---------------- 描述 ----------------
def 解析描述(行们, 表, 内容物行):
    """描述的每一行 → [{名, 键, 值}]。键是输出项（转寄地址/收件人/…/其他/合写地址），不认识的是 None。
    规则见 architecture/讨论_飞书任务读取.md 第三节。"""
    项们, 当前, 等冒号 = [], None, False

    def 新项(名, 键, 值):
        项 = {"名": 名.strip(), "键": 键, "值": [值] if 值 else []}
        项们.append(项)
        return 项

    for 原 in 行们:
        s = 原.strip()
        if 等冒号 and s[:1] in ("：", ":"):
            当前["值"].append(s[1:].strip())
            等冒号 = False
            continue
        等冒号 = False
        if not s:
            if 当前:
                当前["值"].append("")
            continue
        m = re.match(r"^(.{1,40}?)\s*[：:]\s*(.*)$", s)
        if m:
            规 = 规范(m[1])
            if 规 in 表:
                当前 = 新项(m[1], 表[规], m[2])
                continue
            if 当前 and 当前["键"] == "内容物" and (规 in 内容物行 or len(规) > 8):
                当前["值"].append(s)          # “数量：1”、商品名里带冒号的行：算内容物
                continue
            if len(规) <= 8 and 规 not in 内容物行:
                当前 = 新项(m[1], None, m[2])  # 不认识的项目
                continue
        else:
            if 规范(s) in 表 and len(s) <= 20:   # 名称单独一行，冒号在下一行
                当前 = 新项(s, 表[规范(s)], "")
                等冒号 = True
                continue
        if 当前:
            当前["值"].append(s)               # 接到上一项后面（地址折行、内容物的商品行等）
        else:
            当前 = 新项("（描述开头）", None, s)
    for 项 in 项们:
        值 = re.sub(r"\n{2,}", "\n", "\n".join(项["值"])).strip()
        if 项["名"].startswith("【"):
            值 = 值.rstrip("】 ").strip()
        项["值"] = 值
    return 项们


def 归纳(项们):
    """→ (输出{项: (原名, 值)}, 其他[(原名, 值)], 提醒[])"""
    输出, 其他, 提醒 = {}, [], []
    for 项 in 项们:
        键, 名, 值 = 项["键"], 项["名"], 项["值"]
        if 键 is None:
            其他.append((名, 值))
            if 名 != "（描述开头）":
                提醒.append(f"⚠ 描述里有不认识的项目“{名}”，放在了其他信息里，请看一下")
            continue
        if 键 == "其他":
            其他.append((名, 值))
            continue
        合写 = 键 == "合写地址"
        if 合写:
            键 = "转寄地址"
        if 键 in 输出 and 输出[键][1] != 见地址:
            其他.append((名, 值))
            提醒.append(f"⚠ “{名}”出现了两次，用的是第一次的，第二次放在其他信息里")
            continue
        输出[键] = (名, 值)
        if 合写:
            for 项名 in ("收件人", "电话"):
                输出.setdefault(项名, (项名, 见地址))
    return 输出, 其他, 提醒


# ---------------- 一条任务 ----------------
def _数字(s):
    return re.sub(r"\D", "", s or "")


def 整理任务(列表标题, 评论数, 详情, 表, 内容物行):
    题 = 解析标题(列表标题)
    项们 = 解析描述(详情.get("描述行") or [], 表, 内容物行)
    输出, 其他, 提醒 = 归纳(项们)
    申请类 = "申请" in 题["类型"]
    字段 = {}
    for 项 in ("转运单号", "会员码", "重量", "位置"):
        字段[项] = 题[项] or "（标题里没有）"
        if not 题[项] and 申请类:
            提醒.append(f"⚠ 标题里读不到{项}")
    if 题["区不一致"]:
        提醒.append(f"⚠ 标题里的区和货架号字母不一样：{题['位置']}")
    # 核对标题和描述
    描述单号值 = 输出.get("入库转运单号", ("", ""))[1].strip()
    描述单号 = re.search(r"\d{6}-\d{6}", 描述单号值)
    if 描述单号值 and 题["转运单号"] and 题["转运单号"] not in 描述单号值:
        提醒.append(f"⚠ 标题和描述的单号不一致：标题 {题['转运单号']}，描述“入库转运单号”是 {描述单号值[:40]}")
    elif 描述单号值 and not 题["转运单号"] and 申请类:
        提醒.append(f"⚠ 标题里没有单号，描述“入库转运单号”是 {(描述单号[0] if 描述单号 else 描述单号值)[:40]}（仅供参考）")
    描述会员 = _数字(输出.get("会员标识码", ("", ""))[1])
    if 描述会员 and 题["会员码"] and 描述会员 != 题["会员码"]:
        提醒.append(f"⚠ 标题和描述的会员码不一致：标题 {题['会员码']}，描述“会员标识码”是 {输出['会员标识码'][1]}")
    # 描述里的项目
    名称 = {}
    for 项 in ("转寄地址", "收件人", "电话", "寄件人", "内容物"):
        if 项 in 输出:
            原名, 值 = 输出[项]
            字段[项] = 值 if 值 else "（空）"
            if "退货" in 原名 and 值 != 见地址:
                名称[项] = 原名         # 退货类保留原名（“退货地址”“退货收件人”“退货地址／收件人姓名／电话”）
        else:
            字段[项] = "（描述里没有）"
    if not (详情.get("描述行") or []):
        提醒.append("⚠ 这条任务没有描述（或描述读不到）")
    # 评论（从最早到最新，和飞书里一样）
    评论们 = 详情.get("评论")
    评论列表, 评论提醒 = [], ""
    if 评论们 is None:
        字段["评论"] = "（读不到评论区）"
        提醒.append("⚠ 读不到评论区")
    else:
        for c in 评论们:
            文 = c["文"] or ""
            if c["图"]:
                文 = (文 + " [图片]").strip()
            评论列表.append(f"{c['人']} {c['时间']}：{文 or '（空）'}")
        字段["评论"] = "\n".join(评论列表) if 评论列表 else "（没有评论）"
        应有 = None if 评论数 in (None, "") else (999 if str(评论数).endswith("+") else int(评论数))
        if 详情.get("有更早") or (应有 is not None and 应有 > len(评论们)):
            评论提醒 = f"⚠ 评论不完整，只读到最近 {len(评论们)} 条（共 {评论数} 条）"
            字段["评论"] = 评论提醒 + "\n" + 字段["评论"]
            提醒.append(f"⚠ 评论不完整，只读到最近 {len(评论们)} 条")
    其他行 = [f"{名}：{值 or '（空）'}" for 名, 值 in 其他
            if 规范(名) not in ("会员标识码", "入库转运单号")]
    if 详情.get("描述图片"):
        其他行.append(f"描述里有 {详情['描述图片']} 张图片（程序不读图片）")
    if 详情.get("标题") and re.sub(r"\s+", "", 详情["标题"]) != re.sub(r"\s+", "", 列表标题):
        提醒.append(f"⚠ 打开详情时标题和列表里的不一样（可能刚被改过），现在是：{详情['标题'][:60]}")
    # 邮编：按官方数据查地址的邮编，并核对地址里写的（2026-10-24 小柒要求）
    另写 = next((值 for 名, 值 in 其他 if 规范(名) in ("邮编", "郵便番号")), None)
    邮编结果 = 邮编.查(字段["转寄地址"] if not 字段["转寄地址"].startswith("（") else "", 另写)
    if 邮编结果["显示"].startswith("⚠"):
        提醒.append("⚠ 邮编/地址：" + 邮编结果["显示"].lstrip("⚠ "))
    return {"标题": 列表标题, "状态": 题["状态"], "类型": 题["类型"], "字段": 字段, "名称": 名称,
            "其他": "\n".join(其他行), "其他列表": 其他行, "评论列表": 评论列表, "评论提醒": 评论提醒,
            "提醒": 提醒, "读取": "成功", "邮编": 邮编结果,
            "品名参考": 品名参考(字段["内容物"], 读品名表()) or "（没有参考，请自己填）"}



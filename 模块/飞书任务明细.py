预览字数 = 40


def _截(文字, 字数=预览字数):
    """预览里每一条只显示第一行的前 40 个字，多了加“……”。"""
    首行 = 文字.split("\n")[0]
    return 首行[:字数] + "……" if len(首行) > 字数 or "\n" in 文字 else 首行


def 内容物件们(内容物):
    """内容物分成一件一件：单独一行的“数量：1”“数量 10”“数量2”接在上一件商品后面。"""
    if not 内容物 or 内容物.startswith("（"):
        return []
    件们 = []
    for 行 in 内容物.split("\n"):
        s = 行.strip()
        if not s:
            continue
        if 件们 and re.match(r"^数量\s*[：:]?\s*\d", s):
            件们[-1] = (件们[-1][0], s)
        else:
            件们.append((s, ""))
    return 件们


def _截件(件):
    主, 数量 = 件
    主 = 主[:预览字数] + "……" if len(主) > 预览字数 else 主
    return f"{主}　{数量}" if 数量 else 主


可折叠项 = {"内容物": "件", "评论": "条评论", "其他信息": "项"}


def 折叠(任务, 项):
    """内容物：前两件；评论：最早一条 + 最新一条；其他信息：前两项（小柒 2026-10-24 确认）。
    返回 (预览行们, 收起了几条)；不需要折叠时返回 None。“评论不完整”的提醒始终显示在最前面。"""
    头 = []
    if 项 == "内容物":
        件们 = 内容物件们(任务["字段"]["内容物"])
        预览 = [_截件(x) for x in 件们[:2]]
        藏 = len(件们) - len(预览)
        if not 件们 or (藏 == 0 and "\n".join(预览) == 任务["字段"]["内容物"]):
            return None
        return 预览, 藏
    if 项 == "评论":
        列表, 头 = 任务.get("评论列表") or [], ([任务["评论提醒"]] if 任务.get("评论提醒") else [])
        挑 = [列表[0], 列表[-1]] if len(列表) > 2 else 列表
    else:
        列表 = 任务.get("其他列表") or []
        挑 = 列表[:2]
    藏 = len(列表) - len(挑)
    if 藏 == 0 and all(_截(x) == x for x in 挑):
        return None
    return 头 + [_截(x) for x in 挑], 藏


def _还有(项, 藏, 动作):
    return f"……{'还有 %d %s，' % (藏, 可折叠项[项]) if 藏 else ''}{动作}"


def 任务行们(任务, 可折叠=False):
    """一条任务 → [[项目, 内容], …]。可折叠=True（窗口用）时，评论和其他信息的内容是
    {"预览", "全部"}：平时显示预览，单击展开全部；复制时复制全部。"""
    if 任务["读取"] != "成功":
        return [["读取结果", f"⚠ {任务['读取']}：{任务.get('错误', '')}"]]
    行们 = []
    for 项 in 输出顺序:
        名 = 任务["名称"].get(项, 项)
        值 = 任务["字段"][项]
        if 可折叠 and 项 in 可折叠项 and (折 := 折叠(任务, 项)):
            预览, 藏 = 折
            值 = {"预览": "\n".join(预览 + [_还有(项, 藏, "单击展开全部")]), "全部": 值}
        行们.append([名, 值])
    if 任务["其他"]:
        值 = 任务["其他"]
        if 可折叠 and (折 := 折叠(任务, "其他信息")):
            预览, 藏 = 折
            值 = {"预览": "\n".join(预览 + [_还有("其他信息", 藏, "单击展开全部")]), "全部": 值}
        行们.append(["其他信息", 值])
    if 任务["提醒"]:
        行们.append(["⚠ 提醒", "\n".join(句.lstrip("⚠ ") for 句 in 任务["提醒"])])
    return 行们


def _卡片元素(名, 任务):
    """飞书卡片里一条任务：要点直接显示；评论、其他信息显示预览 + 折叠面板（点开看全部）；⚠ 提醒全部显示。"""
    if 任务["读取"] != "成功":
        return [表格.文字元素(f"**{名}**\n⚠ {任务['读取']}：{任务.get('错误', '')}")]
    缩进 = lambda s: s.replace("\n", "\n　　")
    行 = [f"**{任务['名称'].get(项, 项)}**：{缩进(任务['字段'][项])}" for 项 in 输出顺序 if 项 not in 可折叠项]
    元素们 = [表格.文字元素(f"**{名}**\n" + "\n".join(行))]
    for 项, 全部 in (("内容物", 任务["字段"]["内容物"]), ("评论", 任务["字段"]["评论"]), ("其他信息", 任务["其他"])):
        if not 全部:
            continue
        折 = 折叠(任务, 项)
        if 折 is None:
            元素们.append(表格.文字元素(f"**{项}**：{缩进(全部)}"))
            continue
        预览, 藏 = 折
        元素们.append(表格.文字元素(f"**{项}**：{缩进(chr(10).join(预览))}"))
        元素们.append(表格.折叠面板(_还有(项, 藏, "点开看全部"), [表格.文字元素(全部)]))
    if 任务["提醒"]:
        元素们.append(表格.文字元素("**⚠ 提醒**：" + 缩进("\n".join(句.lstrip("⚠ ") for 句 in 任务["提醒"]))))
    return 元素们


def 地址里的邮编(地址):
    """地址里写着的邮编（〒544-0005、653-0836、邮编：9518061 这几种写法），没有返回 None。"""
    m = re.search(r"(?<!\d)(\d{3})\s*[-‐－ー―−]?\s*(\d{4})(?!\d)", 地址 or "")
    return f"{m[1]}-{m[2]}" if m else None



# ---------------- 对照表 ----------------
def 规范(名):
    """比对前统一写法：去空格、繁体电话、【】、名称后面的括号说明。"""
    s = re.sub(r"\s+", "", 名).replace("電", "电").replace("話", "话")
    if s.startswith("【"):
        s = s.replace("【", "").replace("】", "")
    s = re.sub(r"(【[^】]*】|（[^）]*）|\([^)]*\))+$", "", s)
    return s.replace("【", "").replace("】", "")


def 读对照表(文件=对照表文件):
    """返回 (名称→输出项, 内容物里的行名集合)。读不到或写错时报错（不会瞎猜）。"""
    try:
        文字 = Path(文件).read_text(encoding="utf-8-sig")
    except Exception as e:
        raise 自动化错误(程序出错, f"读不到 飞书对照表.txt：{e}")
    表, 内容物行 = {}, set()
    for 行号, 行 in enumerate(文字.splitlines(), 1):
        s = 行.strip()
        if not s or s.startswith("#"):
            continue
        if "=" not in s:
            raise 自动化错误(程序出错, f"飞书对照表.txt 第 {行号} 行少了“=”：{s}")
        项, 右 = (x.strip() for x in s.split("=", 1))
        写法们 = [w.strip() for w in re.split(r"[、,，]", 右) if w.strip()]
        if 项 == "内容物里的行":
            内容物行 |= {规范(w) for w in 写法们}
        else:
            for w in 写法们:
                表[规范(w)] = 项
    for 必须 in ("转寄地址", "收件人", "电话", "寄件人", "内容物", "会员标识码", "入库转运单号"):
        if 必须 not in 表.values():
            raise 自动化错误(程序出错, f"飞书对照表.txt 里缺少“{必须} = …”这一行")
    return 表, 内容物行



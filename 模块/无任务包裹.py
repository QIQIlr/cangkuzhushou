# 职责：查询所选范围（默认瑞江仓库 = D区 + E区，在窗口的模块设置里改）“已挂起 + 任务小类=无任务”的包裹，列出转运单号。只读，不改任何 WMS 数据。
# 输入：已登录的 WMS 页面 + 运行记录 + 参数（查询范围：仓库或单独的区，规则和待处理模块一样，见 公共\查询范围.py；小柒 2026-10-24）。
#   选了仓库就查它包含的每个区；结果仍按区列出数量和单号，最后一行合计。
# 输出：结果字典 {状态, 数量, 区域列表, 错误信息}
#   状态：成功 / 无数据 / 不完整 / 失败
#   - 无数据：页面明确显示“共 0 条记录”
#   - 不完整：读到的单号个数和“共 N 条”对不上
#   - 失败：读不到总数或页面出错——这时绝不报 0
# 步骤（小柒 2026-10-22 确认）：首页 → 仓库管理 → 数据管理 → 包裹管理 → 已挂起 → 展开
#   → 任务小类选“无任务” → 清空“签收时间” → 区域选设置里勾选的一个区 → 查询 → 读全部页；每个区各查一次。
# 一个区域失败不影响另一个区域。
# 排错：每次运行的详细记录在 日志\日期_时间_无任务包裹\ 文件夹里。

def _等查询结果(页面, 动作, 页码=1):
    """做一个动作（点查询/翻页），等页面自己的查询请求返回，返回 (参数, 数据)。"""
    try:
        with 页面.expect_response(
                lambda r: 查询接口 in r.url and f"pageNo={页码}" in r.url, timeout=30000) as 等待:
            动作()
        回应 = 等待.value
        数据 = 回应.json()
    except 自动化错误:
        raise
    except Exception as e:
        错误 = 归类(e)
        if 错误.类型 in (页面改版, 浏览器被关):
            raise 错误
        raise 自动化错误(网络超时, "点击后 30 秒内没有拿到查询结果。")
    if not isinstance(数据, dict) or 数据.get("code") != 0 or "data" not in 数据:
        raise 自动化错误(网络超时, "WMS 返回了错误：" + str(数据)[:200])
    return parse_qs(urlparse(回应.url).query), 数据["data"]


def 查询一个区域(页面, 区域, 记录=None):
    """在已设好“已挂起 / 无任务 / 无签收时间”的页面上，查一个区域，返回 (状态, 总数, 单号列表, 说明)。"""
    下拉选择(页面, "区域", 区域)
    参数, 数据 = _等查询结果(页面, lambda: 页面.get_by_role("button", name="查询").first.click())

    # 核对：查询条件确实是我们要的
    区域字母 = None if 区域 == "全部" else 区域.replace("区", "")   # “全部”只在测试翻页时用
    应有 = {"packagesStatus": "11", "taskType": "-1", "shelvesRegionNum": 区域字母}
    for 键, 值 in 应有.items():
        if 参数.get(键, [None])[0] != 值:
            raise 自动化错误(页面改版, f"查询条件没有生效（{键}={参数.get(键)}），本次结果不可信。")
    if any("time" in 键.lower() for 键 in 参数):
        raise 自动化错误(页面改版, "签收时间条件没有清空，本次结果不可信。")

    总数 = 数据.get("total")
    if not isinstance(总数, int):
        raise 自动化错误(数据不完整, "读不到总条数。")
    try:   # 核对：页面上显示的“共 N 条记录”和读到的一致
        页面.locator("span").filter(has_text=re.compile(f"^共 {总数} 条记录$")).first.wait_for(timeout=10000)
    except Exception:
        raise 自动化错误(数据不完整, f"页面显示的条数和读到的 {总数} 不一致。")

    单号 = [项.get("transportNum") for 项 in 数据.get("list", [])]
    总页数 = math.ceil(总数 / 每页条数)
    if 记录:
        记录.写(f"    共 {总数} 条，{总页数} 页")
    for 页码 in range(2, 总页数 + 1):
        下一页 = 页面.locator(".vxe-pager--next-btn:visible").first
        _, 数据 = _等查询结果(页面, 下一页.click, 页码)
        单号 += [项.get("transportNum") for 项 in 数据.get("list", [])]
        if 记录:
            记录.写(f"    已读第 {页码} 页")

    单号 = [号 for 号 in 单号 if 号]
    if 总数 == 0:
        return "无数据", 0, [], ""
    if len(单号) != 总数 or len(set(单号)) != len(单号):
        return "不完整", 总数, 单号, f"应有 {总数} 条，实际读到 {len(单号)} 条（去重后 {len(set(单号))}）"
    return "成功", 总数, 单号, ""


def 失败结果(e, 开始时间, 参数=None):
    return {"状态": "失败", "数量": None, "开始时间": 开始时间,
            "区域列表": [{"区域": 区, "状态": "失败", "数量": "", "单号": []} for 区 in 查询范围.要查的区((参数 or 默认参数).get("查询范围"))],
            "错误信息": e.一句话(模块名), "错误列表": [e]}


def 运行(页面, 记录, 参数=None):
    """页面需已登录。
    返回 {状态, 数量, 开始时间, 区域列表[{区域, 状态, 数量, 单号}], 错误信息, 错误列表}"""
    开始时间 = datetime.now()
    区域列表, 错误, 合计 = [], [], 0
    选择 = (参数 or 默认参数).get("查询范围")
    要查 = 查询范围.要查的区(选择)
    范围提醒 = 查询范围.整理(选择)[1]
    if 范围提醒:
        记录.写("查询范围按规则整理：" + "；".join(范围提醒))
    if not 要查:
        return 失败结果(自动化错误(设置有误, f"查询范围是空的（设置里是：{选择}），不能查。"), 开始时间, 参数)
    try:
        with 记录.步骤("进入 仓库管理 → 数据管理 → 包裹管理"):
            进入页面(页面, ["仓库管理", "数据管理", "包裹管理"], 等待接口=查询接口)
        with 记录.步骤("点击“已挂起”"):
            _等查询结果(页面, lambda: 页面.locator(".el-tabs__item").filter(
                has_text=re.compile("^已挂起")).first.click())
        with 记录.步骤("展开更多条件"):
            页面.get_by_text("展开").first.click()
            页面.wait_for_timeout(800)
        with 记录.步骤("任务小类选“无任务”"):
            下拉选择(页面, "任务小类", "无任务")
        with 记录.步骤("清空“签收时间”"):
            清空日期(页面, "签收时间")
    except 自动化错误 as e:
        return 失败结果(e, 开始时间, 参数)

    for 区域 in 要查:
        try:
            with 记录.步骤(f"查询 {区域}"):
                状态, 总数, 单号, 说明 = 查询一个区域(页面, 区域, 记录)
                记录.写(f"    结果：{状态}，{总数} 个" + (f"（{说明}）" if 说明 else ""))
        except 自动化错误 as e:
            区域列表.append({"区域": 区域, "状态": "失败", "数量": "", "单号": []})
            错误.append(e)
            if e.类型 in 立刻停下:      # WMS 弹出账号/系统提示：后面的区不再查（体检 2026-10-28）
                记录.写("    WMS 弹出了提示，按规矩立刻停下，后面的区不再查")
                已有 = {区["区域"] for 区 in 区域列表}
                区域列表 += [{"区域": 区, "状态": "失败", "数量": "", "单号": []} for 区 in 要查 if 区 not in 已有]
                break
            continue
        区域列表.append({"区域": 区域, "状态": 状态, "数量": 总数, "单号": 单号})
        合计 += 总数
        if 状态 == "不完整":
            e = 自动化错误(数据不完整, 说明)
            e.步骤 = f"查询 {区域}"
            错误.append(e)

    状态表 = [区["状态"] for 区 in 区域列表]
    if "失败" in 状态表:
        总状态 = "失败"
    elif "不完整" in 状态表:
        总状态 = "不完整"
    elif all(s == "无数据" for s in 状态表):
        总状态 = "无数据"
    else:
        总状态 = "成功"
    return {"状态": 总状态, "数量": None if 总状态 == "失败" else 合计, "开始时间": 开始时间,
            "区域列表": 区域列表, "范围提醒": 范围提醒,
            "错误信息": "；".join(e.一句话(模块名) for e in 错误), "错误列表": 错误}


def 做表(结果):
    """返回 (汇总列名, 汇总行们, 分组)。
    汇总：区域 | 数量 | 状态，最后一行合计；分组：[(区域, [单号…]), …]，只含有单号的区域。"""
    汇总, 分组 = [], []
    for 区 in 结果["区域列表"]:
        if 区["状态"] == "失败":
            汇总.append([区["区域"], "失败", "⚠ 没查到"])
            continue
        标 = {"成功": "✔", "无数据": "无", "不完整": "⚠ 不完整"}.get(区["状态"], 区["状态"])
        汇总.append([区["区域"], 区["数量"], 标])
        if 区["单号"]:
            分组.append((区["区域"], list(区["单号"])))
    合计 = "失败" if 结果["数量"] is None else 结果["数量"]
    汇总.append(["**合计**", f"**{合计}**", ""])
    return ["区域", "数量", "状态"], 汇总, 分组


def 复制文字(区域, 单号们, 时间):
    """“复制本区全部单号”和卡片里文字块的内容：标题 + 每行“序号<Tab>单号”。"""
    return 表格.单号文字表(单号们, f"{区域} {模块参数.显示名(模块名)} {len(单号们)} 个（截至 {时间:%m/%d %H:%M}）")


def 组成消息(结果, 文件夹名, 用时=None):
    """飞书卡片：上面总览表，下面每个有单号的区一个折叠面板（默认收起，展开是可复制的文字表）。
    内容超过 18KB 时按区拆成几张卡片（不丢单号）。窗口：总览 + 点区看明细 + 一键复制。另存 Excel。"""
    时间 = 结果["开始时间"]
    合计 = 结果["数量"]
    名 = 模块参数.显示名(模块名)   # 窗口里改过的名字
    标题 = f"{名}（截至 {时间:%m/%d %H:%M}）" + (f"共 {合计} 个" if 合计 is not None else "")
    汇总列, 汇总行, 分组 = 做表(结果)
    备注 = [f"⚠ 查询范围按规则整理：{句}（请到模块设置里确认一下）" for 句 in 结果.get("范围提醒", [])]
    if 结果["状态"] == "无数据":
        备注.append("所选区域都没有无任务包裹 ✔")
    if 结果["状态"] not in ("成功", "无数据"):
        备注.append(f"⚠ 状态：{结果['状态']}" + ("（标“失败”的区域没查到，不是 0）" if 结果["状态"] != "不完整" else ""))
        for e in 结果.get("错误列表", []):
            备注.append(e.一句话(模块名))
        备注.append(f"日志：{文件夹名}")
    颜色 = {"成功": "blue", "无数据": "blue", "不完整": "orange"}.get(结果["状态"], "red")

    头 = [表格.表格元素(汇总列, 汇总行, ["left", "right", "center"])]
    if 分组:
        头.append(表格.文字元素("<font color='grey'>点下面的区域展开，看全部转运单号（可以拖选复制）</font>"))
    面板们 = []
    for 区域, 单号们 in 分组:
        文字块 = 复制文字(区域, 单号们, 时间)
        if len(文字块.encode("utf-8")) > 15000:   # 一个区单号特别多：拆成几个面板，不丢单号
            每段 = 600
            for k in range(0, len(单号们), 每段):
                段 = 单号们[k:k + 每段]
                面板们.append(表格.折叠面板(f"**{区域}** {len(单号们)} 个（第 {k + 1}～{k + len(段)} 个）",
                                       [表格.代码块(表格.单号文字表(段))]))
        else:
            面板们.append(表格.折叠面板(f"**{区域}** {len(单号们)} 个", [表格.代码块(文字块)]))
    卡片们 = 表格.按大小分卡(标题, 头, 面板们, [表格.文字元素(句) for 句 in 备注], 颜色)

    明细行 = [[i, 区域, 号] for 区域, 单号们 in 分组 for i, 号 in enumerate(单号们, 1)]
    文字 = 标题 + "\n\n" + 表格.文字表格(汇总列, 汇总行)
    for 区域, 单号们 in 分组:
        文字 += "\n\n" + 复制文字(区域, 单号们, 时间)
    if 备注:
        文字 += "\n\n" + "\n".join(备注)
    附件 = None
    try:
        附件 = str(根目录 / "日志" / 文件夹名 / f"{名}_{时间:%Y%m%d_%H%M}.xlsx")
        表格.存Excel多表(附件, 标题, [("汇总", 汇总列, 汇总行), ("明细", ["序号", "区域", "转运单号"], 明细行)], 备注)
    except Exception:
        附件 = None
    # 窗口最上面的一句话结论
    if 结果["状态"] == "失败":
        结论 = f"这次没查到{名}（不是 0）"
    elif 结果["状态"] == "无数据":
        结论 = f"所选区域都没有{名}"
    else:
        部分 = []
        for 区 in 结果["区域列表"]:
            if 区["状态"] == "失败":
                部分.append(f"{区['区域']} 没查到")
            elif 区["数量"]:
                部分.append(f"{区['区域']} {区['数量']} 个" + ("（不完整）" if 区["状态"] == "不完整" else ""))
            else:
                部分.append(f"{区['区域']} 没有")
        结论 = (f"共 {合计} 个：" if 合计 is not None else "") + "，".join(部分)
    return {"文字": 文字, "卡片们": 卡片们, "附件": 附件, "标题": 标题, "备注": 备注,
            "结论": 结论, "提醒们": [句.lstrip("⚠ ") for 句 in 备注 if 句.startswith("⚠ 查询范围")],
            "表们": [("各区域数量", 汇总列, 汇总行)],
            "分组": {"总览": (汇总列, 汇总行),
                     "明细": [(区域, 单号们, 复制文字(区域, 单号们, 时间)) for 区域, 单号们 in 分组]}}, ""

